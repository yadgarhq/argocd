"""`scripts/pin_bump.py --write` reproduces three hand pins byte for byte (ledger 1632 C1).

THE REPLAY PROOF of the plan's section 2. Each case reads the three mechanical
files at a pin pull request's base commit, runs `pin_bump.write_files` on that
tree with the pull request's target, and compares the result with the files the
pull request merged:

    #106  base 1795558 (pin 0.25.9)  -> 0.25.12, merged as 8a2bb79
    #107  base 8a2bb79 (pin 0.25.12) -> 0.25.14, merged as 36059be
    #109  base 36059be (pin 0.25.14) -> 0.25.27, merged as e7403b0

#109's branch was cut from 36059be. Its squash landed on 82b360a (#108), and
#108 touched only `scripts/preflip_gate.py` and its test, so 36059be and
82b360a are identical for the three files replayed here.

MAIN'S WRITER, NOT THE BASE'S. The K3 table is regenerated by the
`test_yadgar_application.py --write` of THIS checkout, copied into the replay
tree beside its `test_no_two_owners.py` (copied, not linked: both resolve their
repository from `Path(__file__).resolve()`). Measured 2026-10-18: the writer's
header and render flags did not change between 1795558 and main, so all three
replays are byte-identical with no writer-format drift to explain.

A GATE, NOT A HOOK: it needs helm 3.18.4 and the registry (`helm pull` of the
parent at the target), and it reads the base and merged files from
raw.githubusercontent.com because CI clones at depth 1.
"""

from __future__ import annotations

import importlib.util
import shutil
import sys
import urllib.request
from pathlib import Path

import pytest

GATES = Path(__file__).resolve().parent
REPOSITORY = GATES.parents[1]

_spec = importlib.util.spec_from_file_location("pin_bump", REPOSITORY / "scripts" / "pin_bump.py")
pb = importlib.util.module_from_spec(_spec)
sys.modules["pin_bump"] = pb
_spec.loader.exec_module(pb)

RAW = "https://raw.githubusercontent.com/yadgarhq/argocd/{sha}/{path}"

REPLAYS = {
    "#106": ("1795558", "0.25.12", "8a2bb79"),
    "#107": ("8a2bb79", "0.25.14", "36059be"),
    "#109": ("36059be", "0.25.27", "e7403b0"),
}


def raw(sha: str, path: str) -> bytes:
    with urllib.request.urlopen(RAW.format(sha=sha, path=path), timeout=30) as response:  # noqa: S310
        return response.read()


@pytest.mark.parametrize("pull_request", sorted(REPLAYS))
def test_the_write_reproduces_the_hand_pin(tmp_path: Path, pull_request: str) -> None:
    base, target, merged = REPLAYS[pull_request]
    for path in pb.MECHANICAL_FILES:
        (tmp_path / path).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / path).write_bytes(raw(base, path))
    for writer in ("test_yadgar_application.py", "test_no_two_owners.py"):
        shutil.copyfile(GATES / writer, tmp_path / "scripts" / "gates" / writer)

    pb.write_files(tmp_path, target)

    differing = [path for path in pb.MECHANICAL_FILES if (tmp_path / path).read_bytes() != raw(merged, path)]
    print(f"[replay] {pull_request}: {base} -> {target}, {len(pb.MECHANICAL_FILES)} file(s) compared with {merged}")
    assert differing == []


# ── the classifier, live, on the #107 range ─────────────────────────────────

# #107's hand evidence (argocd#107's body): 94 objects, one changed, the
# gateway Deployment's image only, at gateway 0.12.11's GHCR tag digest; the
# gateway's literal set unchanged; no -db module moved.
GATEWAY_0_12_11 = "sha256:2c966881ee3ac27671818517ed7cd6fd3a72898b0a93e6bdb34a339848793d22"
ONE_HELM = "only one helm version rendered"


def test_the_107_range_classifies_as_its_hand_evidence(tmp_path: Path) -> None:
    """Green on every rule a live read can judge. CI's `two-owners` job installs helm 3.18.4 alone, so there the
    one remaining reason is the helm count; with two helms (a developer machine) the verdict is ACCEPT."""
    base = "8a2bb79"
    (tmp_path / "applications").mkdir()
    (tmp_path / pb.APPLICATION).write_bytes(raw(base, pb.APPLICATION))
    helms = pb.discover_helms()

    evidence = pb.check(tmp_path, "0.25.14", pb.Net(), helms)

    print(f"[classify] 0.25.12 -> 0.25.14 on helm {', '.join(evidence['helms'])}: reasons {evidence['reasons']}")
    assert [(c["object"], c["digest"]) for c in evidence["changed"]] == [("apps/Deployment//gateway", GATEWAY_0_12_11)]
    assert evidence["objects"] == 94
    assert evidence["boot_audit"] == {"gateway": {"status": "green", "reasons": []}}
    assert evidence["migrations"] == {}
    if len(helms) > 1:
        assert evidence["reasons"] == [] and evidence["accept"] is True
    else:
        assert [r[: len(ONE_HELM)] for r in evidence["reasons"]] == [ONE_HELM] and evidence["accept"] is False
