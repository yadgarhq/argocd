class NoOp(Exception):
    """The target is the pin: nothing to do."""


class Refused(Exception):
    """The request cannot be carried out as asked."""


# ── versions ────────────────────────────────────────────────────────────────

RELEASE = re.compile(r"^v?(\d+)\.(\d+)\.(\d+)$")


def release(version: str) -> tuple[int, int, int] | None:
    """`(major, minor, patch)` of a release version, None for a prerelease or anything else."""
    match = RELEASE.match(version.strip())
    return tuple(int(part) for part in match.groups()) if match else None


def highest_release(tags) -> str:
    """The numeric maximum of the release tags, bare. Prereleases are ignored (ADR-0690: never lexical)."""
    releases = [found for found in (release(tag) for tag in tags) if found]
    if not releases:
        raise Refused("no release tag found")
    return ".".join(str(part) for part in max(releases))


def decide(pin: str, target: str) -> None:
    """Raise NoOp when target is the pin, Refused when it is lower or not a release; None for a bump."""
    wanted, current = release(target), release(pin)
    if wanted is None:
        raise Refused(f"target {target!r} is not a release version X.Y.Z; a prerelease is never pinned")
    if current is None:
        raise Refused(f"the current pin {pin!r} is not a release version X.Y.Z")
    if wanted == current:
        raise NoOp(f"target {target} is the current pin")
    if wanted < current:
        raise Refused(f"target {target} is lower than the current pin {pin}")


# ── the mechanical files ────────────────────────────────────────────────────

# A non-comment line: whitespace, then the key. The comments in yadgar.yaml
# that name `targetRevision` start with `#` and never match.
TARGET_REVISION = re.compile(r"^([ \t]+targetRevision:[ \t]*)(\S+)[ \t]*$", re.M)
CHART_TAG = re.compile(r'^([ \t]*"chart_tag":[ \t]*")([^"]*)(")', re.M)


def parsed_revision(text: str) -> str:
    return str(yaml.safe_load(text)["spec"]["source"]["targetRevision"])


def current_pin(text: str) -> str:
    matches = TARGET_REVISION.findall(text)
    if len(matches) != 1:
        raise Refused(f"`targetRevision:` matched {len(matches)} line(s) in {APPLICATION}; exactly 1 is rewritten")
    return matches[0][1]


def rewrite_target_revision(text: str, target: str) -> tuple[str, str]:
    """`(new text, old revision)`, with the one `targetRevision:` line moved and nothing else."""
    old = current_pin(text)
    match = TARGET_REVISION.search(text)
    rewritten = text[: match.start(2)] + target + text[match.end(2) :]
    for document, wanted in ((text, old), (rewritten, target)):
        if parsed_revision(document) != wanted:
            raise Refused(f"the line rewritten is not `spec.source.targetRevision` (YAML reads {parsed_revision(document)!r})")
    return rewritten, old


def rewrite_chart_pin(text: str, target: str) -> str:
    """`chart_tag` set to `v<target>`, every other byte kept."""
    matches = list(CHART_TAG.finditer(text))
    if len(matches) != 1:
        raise Refused(f'`"chart_tag":` matched {len(matches)} line(s) in {CHART_PIN}; exactly 1 is rewritten')
    match = matches[0]
    rewritten = text[: match.start(2)] + f"v{target}" + text[match.end(2) :]
    if json.loads(rewritten).get("chart_tag") != f"v{target}":
        raise Refused(f"{CHART_PIN} does not parse to the new tag after the edit")
    return rewritten


def modules_of(chart_yaml: str) -> dict[str, str]:
    """`{dependency name: version}` of a parent `chart/Chart.yaml`."""
    return {str(d["name"]): str(d["version"]) for d in yaml.safe_load(chart_yaml).get("dependencies") or []}


# ── helm and the gates' helpers ─────────────────────────────────────────────


def gate(name: str):
    """A module of `scripts/gates/`, imported by name as the gates import each other."""
    if str(GATES) not in sys.path:
        sys.path.insert(0, str(GATES))
    return importlib.import_module(name)


def helm_version(binary: str) -> str:
    finished = subprocess.run([binary, "version", "--short"], capture_output=True, text=True, check=True)
    return finished.stdout.strip().split("+")[0]


def discover_helms() -> dict[str, str]:
    """`{version: binary}`, one binary per distinct helm version."""
    configured = os.environ.get("PIN_BUMP_HELMS")
    candidates = configured.split(os.pathsep) if configured else list(DEFAULT_HELMS)
    found: dict[str, str] = {}
    for candidate in candidates:
        binary = shutil.which(candidate) or (candidate if Path(candidate).is_file() else None)
        if binary:
            found.setdefault(helm_version(binary), str(Path(binary).resolve()))
    return found


@contextlib.contextmanager
def helm_on_path(binary: str):
    """`helm` on PATH is `binary` inside the block: the gates call `helm` by name."""
    with tempfile.TemporaryDirectory() as scratch:
        (Path(scratch) / "helm").symlink_to(binary)
        previous = os.environ.get("PATH", "")
        os.environ["PATH"] = scratch + os.pathsep + previous
        try:
            yield
        finally:
            os.environ["PATH"] = previous


def render(application_text: str, version: str, binary: str) -> list:
    """The parent at `version`, with this Application's `valuesObject`, through the gates' `parent_render`."""
    with tempfile.TemporaryDirectory() as scratch:
        tree = Path(scratch)
        (tree / "applications").mkdir()
        (tree / APPLICATION).write_text(rewrite_target_revision(application_text, version)[0])
        with helm_on_path(binary):
            return gate("test_no_two_owners").parent_render(tree)


# ── E1: the render classifier ───────────────────────────────────────────────


@dataclass
class Verdict:
    accept: bool
    reasons: list[str] = field(default_factory=list)
    changed: list[dict] = field(default_factory=list)
    objects: int = 0
    helms: list[str] = field(default_factory=list)


def objects_of(documents: list) -> dict[str, dict]:
    key = gate("test_yadgar_application").object_key
    return {key(d): d for d in documents if isinstance(d, dict) and d.get("kind")}


def field_paths(old, new, path: str = "") -> list[str]:
    """Every path where `old` and `new` differ; lists of equal length are compared by index."""
    if isinstance(old, dict) and isinstance(new, dict):
        return [
            found
            for key in sorted(set(old) | set(new))
            for found in field_paths(old.get(key), new.get(key), f"{path}.{key}".lstrip("."))
        ]
    if isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        return [found for i, (a, b) in enumerate(zip(old, new, strict=True)) for found in field_paths(a, b, f"{path}[{i}]")]
    return [] if old == new else [path or "<root>"]


def at(document, path: str):
    node = document
    for part in re.findall(r"[^.\[\]]+|\[\d+\]", path):
        node = node[int(part[1:-1])] if part.startswith("[") else node[part]
    return node


def split_image(reference: str) -> tuple[str, str]:
    """`(repository, digest)` of `repo[:tag][@digest]`."""
    named, _, digest = reference.partition("@")
    last = named.rsplit("/", 1)[-1]
    repository = named.rsplit(":", 1)[0] if ":" in last else named
    return repository, digest


def module_moves(old_modules: dict[str, str], new_modules: dict[str, str]) -> list[str]:
    reasons = []
    for name in sorted(set(old_modules) ^ set(new_modules)):
        side = "added to" if name in new_modules else "removed from"
        reasons.append(f"dependency {name} {side} the parent Chart.yaml")
    if old_modules.get(PLATFORM) != new_modules.get(PLATFORM):
        reasons.append(
            f"platform moved {old_modules.get(PLATFORM)} -> {new_modules.get(PLATFORM)}: "
            "the five operator Applications move with it; interim block; lifted by car C10 per ADR-0948 R5"
        )
    return reasons


def classify(renders: dict, old_modules: dict, new_modules: dict, digest_of) -> Verdict:
    """E1. `renders` is `{helm version: (base documents, head documents)}`."""
    digests = gate("test_yadgar_application").digests
    helms = sorted(renders)
    reasons: list[str] = []
    if len(helms) < 2:
        reasons.append(f"only one helm version rendered ({', '.join(helms) or 'none'}); acceptance needs two that agree")
    first = helms[0]
    for other in helms[1:]:
        for side, index in (("base", 0), ("head", 1)):
            a, b = digests(renders[first][index]), digests(renders[other][index])
            if a != b:
                differing = sorted(k for k in a.keys() | b.keys() if a.get(k) != b.get(k))
                reasons.append(f"helm {first} and helm {other} disagree at the {side} pin: {', '.join(differing)}")

    reasons += module_moves(old_modules, new_modules)

    base, head = (objects_of(documents) for documents in renders[first])
    reasons += [f"object removed: {key}" for key in sorted(base.keys() - head.keys())]
    reasons += [f"object added: {key}" for key in sorted(head.keys() - base.keys())]

    changed: list[dict] = []
    for key in sorted(base.keys() & head.keys()):
        old, new = base[key], head[key]
        for path in field_paths(old, new):
            if old.get("kind") not in WORKLOAD_KINDS or not IMAGE_FIELD.match(path):
                reasons.append(f"{key}: field {path} changed; only a workload's container image may change")
                continue
            entry, problems = judge_image(key, path, at(old, path), at(new, path), old_modules, new_modules, digest_of)
            reasons += problems
            if entry:
                changed.append(entry)

    return Verdict(accept=not reasons, reasons=reasons, changed=changed, objects=len(head), helms=helms)


def judge_image(key, path, old_image, new_image, old_modules, new_modules, digest_of) -> tuple[dict | None, list[str]]:
    """One changed image against the rules; `(evidence entry or None, problems)`."""
    old_repository, _ = split_image(str(old_image))
    repository, digest = split_image(str(new_image))
    problems = []
    if repository != old_repository:
        problems.append(f"{key}: {path} repository changed {old_repository} -> {repository}")
    module = repository[len(REGISTRY) :] if repository.startswith(REGISTRY) else ""
    if not module or "/" in module:
        problems.append(f"{key}: {path} repository {repository} is not {REGISTRY}<module>")
        return None, problems
    if module not in new_modules:
        problems.append(f"{key}: {path} image of {module}, which is no dependency of the parent")
        return None, problems
    version = new_modules[module]
    if old_modules.get(module) == version:
        problems.append(f"{key}: {path} image of module {module} changed but its version did not move ({version})")
        return None, problems
    try:
        expected = digest_of(module, version)
    except Exception as error:  # noqa: BLE001  (an unreadable registry is a red, never a green)
        problems.append(f"{key}: the GHCR tag digest of {module}:{version} could not be read ({error})")
        return None, problems
    if digest != expected:
        problems.append(
            f"{key}: {path} digest {digest or '<none>'} is not the GHCR tag digest of {module}:{version} ({expected})"
        )
    return {"object": key, "field": path, "module": module, "version": version, "digest": digest}, problems


# ── reading Rust source ─────────────────────────────────────────────────────

TEST_MODULE = re.compile(r"#\[cfg\(test\)\]\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{")
CHAR_LITERAL = re.compile(r"'(?:\\u\{[0-9a-fA-F]{1,6}\}|\\.|[^\\'\n])'")
RAW_STRING = re.compile(r'b?r(#*)"')


def code_mask(text: str) -> str:
    """`text` with the inside of every comment, string and char literal blanked to spaces, same length.

    What a brace counter or a call-site search reads, so a `{` in `"{"`, `'{'`,
    `r#"{"#`, `// {` or `/* { */` is never code. Newlines are kept. A lifetime
    (`'a`) is not a char literal and stays code.
    """
    out = list(text)
    length = len(text)

    def blank(start: int, stop: int) -> None:
        for k in range(start, stop):
            if out[k] != "\n":
                out[k] = " "

    i = 0
    while i < length:
        if text.startswith("//", i):
            stop = text.find("\n", i)
            stop = length if stop < 0 else stop
            blank(i, stop)
            i = stop
            continue
        if text.startswith("/*", i):
            depth, j = 0, i
            while j < length:
                if text.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif text.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                    if depth == 0:
                        break
                else:
                    j += 1
            blank(i, j)
            i = j
            continue
        boundary = i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")
        raw = RAW_STRING.match(text, i) if boundary and text[i] in "rb" else None
        if raw:
            close = '"' + raw.group(1)
            stop = text.find(close, raw.end())
            stop = length if stop < 0 else stop
            blank(raw.end(), stop)
            i = min(length, stop + len(close))
            continue
        if text[i] == '"':
            j = i + 1
            while j < length and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            blank(i + 1, min(j, length))
            i = j + 1
            continue
        if text[i] == "'" and (char := CHAR_LITERAL.match(text, i)):
            blank(i + 1, char.end() - 1)
            i = char.end()
            continue
        i += 1
    return "".join(out)


def matching_brace(mask: str, opening: int) -> int:
    """Index just past the `}` closing the `{` at `opening`, counted on a `code_mask`."""
    depth = 0
    for index in range(opening, len(mask)):
        if mask[index] == "{":
            depth += 1
        elif mask[index] == "}":
            depth -= 1
            if depth == 0:
                return index + 1
    return len(mask)


def without_test_modules(text: str) -> str:
    while match := TEST_MODULE.search(mask := code_mask(text)):
        text = text[: match.start()] + text[matching_brace(mask, match.end() - 1) :]
    return text


def is_test_path(path: str) -> bool:
    parts = Path(path).parts
    name = parts[-1]
    return "tests" in parts[:-1] or name == "tests.rs" or name.endswith(("_tests.rs", "_test.rs"))


def production_sources(source: dict[str, str]) -> dict[str, str]:
    """Non-test `src/**/*.rs`, with `#[cfg(test)] mod … { }` blocks removed."""
    return {
        path: without_test_modules(text)
        for path, text in sorted(source.items())
        if path.startswith("src/") and path.endswith(".rs") and not is_test_path(path)
    }


# ── E3: the boot audit ──────────────────────────────────────────────────────

# AN UPPER-SNAKE LITERAL COUNTS ONLY AS AN ENV NAME AT AN ENV-READ CALL SITE
# (coordinator ruling, ledger 1632): error codes such as `NOT_FOUND` and
# `PROJECT_ARCHIVED` are not env names. The call sites are every pattern the
# seven module repos and seeder use, grepped 2026-10-18 at their latest tags:
#
#   required  `env_required*(…)` (`env_required`, `_allow_empty`, `_chart`,
#             `_named`), `env_parsed(…)` (task-db) and `parse_bucket_env(…)`
#             (gateway): each refuses to boot on an absent key;
#   read      `std::env::var(…)`, `env::var_os(…)`, and a call to a lookup
#             closure parameter typed `impl Fn(&str) -> Option<String>` —
#             gateway's `from_lookup(lookup: …)` reads `lookup(KEY)`, the -db
#             modules' `boot(env: …)` read `env(KEY)`;
#   wrapped   a local closure whose body calls one of the above — seeder's
#             `let required = |var| match lookup(var) …` — read only inside
#             the block that binds it (a `let` cannot be named outside it, so
#             gateway's tls.rs `let get = |suffix| …` never makes axum's
#             `get(whoami)` in another fn a read; a closure whose name
#             appears in that block other than as a call — passed, returned,
#             stored — escapes, and stays a reader crate-wide), and a `fn` or
#             `macro_rules!` whose body calls one keyed on its own parameter
#             (`fn get(k) { std::env::var(k) }`, `req!($k)`) are readers too,
#             required ones when the name says `required` or the body calls a
#             required reader. Followed to a fixpoint.
#
# The key is the first or second argument: a string literal, or a `const` of
# type `&str` defined anywhere in the crate, by bare or path-qualified name
# (`config::HOST`). When the first argument is itself upper-snake (`f(K9, D)`),
# the site is unresolved rather than keyed on the second.
#
# FAIL-CLOSED ON WHAT IT CANNOT READ, by coarse tripwires counted at both tags
# (a false NEEDS-HUMAN is cheap; a false ACCEPT deploys something unvetted):
#
#   - a call site whose key is none of those (`lookup(&format!(…))`, a
#     variable, a const from another crate), counted per (file, enclosing fn,
#     normalised text): any growth is NEEDS-HUMAN;
#   - a call into an env entry point whose reads happen elsewhere —
#     `*from_env*`, `*from_lookup*` (lifecycle's `ServerTls::from_env` reads
#     `{prefix}_TLS_*`, dial's `request_timeout_from_lookup` its own key), or
#     any call handed a reader as an argument: any growth per callee;
#   - the token tripwire (`TRIPWIRE` below): `std::env`, `use std::env`,
#     `env::vars`, `dotenv`, `envy`, `Fn(&str)`, an attribute `env =` (clap):
#     any growth per token;
#   - Cargo.toml and Cargo.lock (`crate_findings`): a moved, unpinnable or
#     overridden `yadgar-*` crate, and any `yadgar-*` change in the lock.
CONST_STR = re.compile(r'\bconst\s+([A-Z][A-Z0-9_]*)\s*:\s*&(?:\'static\s+)?str\s*=\s*"([^"\\]*)"\s*;')
LOOKUP_PARAMETER = re.compile(
    r"\b([a-z_][a-z0-9_]*)\s*:\s*&?\s*(?:impl|dyn)\s+Fn\s*\(\s*&str\s*\)\s*->\s*Option\s*<\s*String\s*>"
)
LOCAL_CLOSURE = re.compile(r"\blet\s+(?:mut\s+)?([a-z_][a-z0-9_]*)\s*=\s*(?:move\s+)?\|([^|]*)\|")
FN_DEFINITION = re.compile(r"\bfn\s+([a-z_][a-z0-9_]*)\s*(?:<[^>{(]*>)?\s*\(")
MACRO_DEFINITION = re.compile(r"\bmacro_rules!\s*([a-z_][a-z0-9_]*)\s*\{")
REQUIRED_READERS = ("env_required\\w*", "env_parsed", "parse_bucket_env")
KEY_ARGUMENT = re.compile(
    r'\s*\(\s*([^()";,]*,\s*)?(?:"([A-Z][A-Z0-9_]*)"|(?:[A-Za-z_]\w*::)*([A-Z][A-Z0-9_]*)\b)(?=\s*[,)])'
)
UPPER_TOKEN = re.compile(r"\b[A-Z][A-Z0-9_]*\b")
CALL = re.compile(r"(?<![\w.])((?:[A-Za-z_]\w*::)*[A-Za-z_]\w*)\s*\(")
NOT_CALLS = frozenset({"if", "while", "match", "for", "return", "fn", "Some", "Ok", "Err", "loop", "in"})
# A call into a shared crate's env read: the keys it reads are not in this source.
ENTRY_POINT = re.compile(r"(?<![\w.])((?:[A-Za-z_]\w*::)*\w*from_(?:env|lookup)\w*)\s*\(")
# THE TOKEN TRIPWIRE: every way to reach the environment that the call-site
# reading above does not model. Counted per tag on the code mask; any count that
# grows is NEEDS-HUMAN. Coarse on purpose: a false NEEDS-HUMAN is cheap, a false
# ACCEPT deploys something unvetted.
TRIPWIRE = {
    "std::env": re.compile(r"\bstd\s*::\s*env\b"),
    "use std::env": re.compile(r"\buse\s+std\s*::\s*env\b"),
    "env::vars": re.compile(r"\benv\s*::\s*vars(?:_os)?\b"),
    "dotenv": re.compile(r"dotenv"),
    "envy": re.compile(r"\benvy\b"),
    "Fn(&str)": re.compile(r"\bFn\s*\(\s*&\s*str\s*\)"),
    "attribute env =": re.compile(r"#\s*!?\s*\[[^\]]*\benv\s*="),
}


def matching_paren(mask: str, opening: int) -> int:
    """Index just past the `)` closing the `(` at `opening`, counted on a `code_mask`."""
    depth = 0
    for index in range(opening, len(mask)):
        depth += {"(": 1, ")": -1}.get(mask[index], 0)
        if depth == 0:
            return index + 1
    return len(mask)


def arguments(mask: str, opening: int) -> list[str]:
    """The top-level arguments of the call whose `(` is at `opening`, as masked text."""
    inner = mask[opening + 1 : matching_paren(mask, opening) - 1]
    parts, depth, current = [], 0, ""
    for char in inner:
        depth += {"(": 1, "[": 1, "{": 1, "<": 1, ")": -1, "]": -1, "}": -1, ">": -1}.get(char, 0)
        if char == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += char
    return [part.strip() for part in parts + [current] if part.strip()]


def bare(argument: str) -> str:
    return re.sub(r"^&\s*(?:mut\s+)?", "", argument).strip()


def reader_call(required: set[str], read: set[str]) -> re.Pattern:
    names = lambda group: "|".join(sorted(group))  # noqa: E731
    pattern = rf"(?P<required>(?<![\w.])(?:{names(required)}))"
    pattern += r"|(?P<read>\benv::var(?:_os)?"
    pattern += rf"|(?<![\w.])(?:{names(read)}))" if read else ")"
    return re.compile(rf"(?:{pattern})(?=\s*\()")


def enclosing_block_end(mask: str, position: int) -> int:
    """Index just past the `}` closing the innermost `{` that encloses `position`, counted on a `code_mask`."""
    depth = 0
    for index in range(position - 1, -1, -1):
        if mask[index] == "}":
            depth += 1
        elif mask[index] == "{":
            if depth == 0:
                return matching_brace(mask, index)
            depth -= 1
    return len(mask)


def wrappers(mask: str) -> list[tuple[str, str, set[str], int, int, tuple[int, int] | None]]:
    """`(kind, name, parameters, body start, body stop, scope)` of every local closure, fn and macro_rules! in
    `mask`. `scope` is a closure's `(binding, end of its enclosing block)`, the only span that can name it;
    None for a fn or macro, which the crate can name anywhere, and for a closure whose value escapes that span."""
    found = []
    for closure in LOCAL_CLOSURE.finditer(mask):
        parameters = set(re.findall(r"([a-z_]\w*)\s*(?::|$|,)", closure.group(2)))
        brace, semicolon = mask.find("{", closure.end()), mask.find(";", closure.end())
        stop = matching_brace(mask, brace) if 0 <= brace < semicolon or semicolon < 0 <= brace else semicolon
        scope: tuple[int, int] | None = (closure.start(), enclosing_block_end(mask, closure.start()))
        uses = re.finditer(rf"(?<![\w.]){re.escape(closure.group(1))}\b(?!\s*\()", mask[closure.end() : scope[1]])
        if next(uses, None) is not None:
            scope = None  # the closure value escapes (passed, returned, stored, aliased): crate-wide, as before
        found.append(("closure", re.escape(closure.group(1)), parameters, closure.end(), stop if stop > 0 else len(mask), scope))
    for function in FN_DEFINITION.finditer(mask):
        close = matching_paren(mask, function.end() - 1)
        parameters = set(re.findall(r"(?:^|[,(])\s*(?:mut\s+)?([a-z_]\w*)\s*:", mask[function.end() - 1 : close]))
        brace = mask.find("{", close)
        if brace >= 0 and ";" not in mask[close:brace]:
            found.append(("fn", re.escape(function.group(1)), parameters, brace, matching_brace(mask, brace), None))
    for macro in MACRO_DEFINITION.finditer(mask):
        stop = matching_brace(mask, macro.end() - 1)
        parameters = {f"${name}" for name in re.findall(r"\$([a-z_]\w*)\s*:", mask[macro.end() : stop])}
        found.append(("macro", re.escape(macro.group(1)) + "!", parameters, macro.end(), stop, None))
    return found


Scopes = dict[str, list[tuple[str, int, int]]]


def visible(scopes: Scopes, matched: str, path: str, position: int) -> bool:
    """Whether the reader call `matched` at `position` in `path` names a reader: always for a crate-wide one,
    and for a closure-only name only inside a block that binds it."""
    spans = scopes.get(re.escape(matched))
    return spans is None or any(p == path and start <= position < stop for p, start, stop in spans)


def readers_of(files: dict[str, str], masks: dict[str, str]) -> tuple[set[str], set[str], Scopes]:
    """`(required reader names, plain reader names, scopes)`: the fixed ones, lookup parameters, and every
    closure, fn or macro_rules! whose body calls a reader keyed on one of its own parameters (or, for a
    closure, at all). `scopes` maps a name read only by closures to the `(path, start, stop)` spans that
    can name it; a name absent from `scopes` is a reader anywhere in the crate."""
    required = set(REQUIRED_READERS)
    read = {re.escape(name) for mask in masks.values() for name in LOOKUP_PARAMETER.findall(mask)}
    crate_wide = required | read
    scopes: Scopes = {}
    every = [(path, w) for path, mask in masks.items() for w in wrappers(mask)]
    done: set[int] = set()
    while True:
        call = reader_call(required, read)
        found = False
        for index, (path, (kind, name, parameters, start, stop, scope)) in enumerate(every):
            if index in done or name in crate_wide:
                continue
            mask = masks[path]
            inner = []
            for match in call.finditer(mask, start, stop):
                if not visible(scopes, match.group(0), path, match.start()):
                    continue
                opening = mask.find("(", match.end())
                keyed = {bare(a) for a in arguments(mask, opening)[:2]} & parameters
                if keyed or kind == "closure":
                    inner.append(match)  # a closure counts on any read; a fn or macro on a parameter-keyed one
            if not inner:
                continue
            plain = name.rstrip("!").replace("\\", "")
            is_required = "required" in plain or any(m.group("required") for m in inner)
            (required if is_required else read).add(name)
            if scope is None:
                crate_wide.add(name)
                scopes.pop(name, None)
            else:
                scopes.setdefault(name, []).append((path, *scope))
            done.add(index)
            found = True
        if not found:
            return required, read, scopes


def enclosing_fn(mask: str, position: int) -> str:
    names = [m.group(1) for m in FN_DEFINITION.finditer(mask, 0, position)]
    return names[-1] if names else "<top>"


def env_sites(source: dict[str, str]) -> tuple[set[str], set[str], Counter]:
    """`(required keys, every key read, unresolved call sites)` of the non-test source.

    An unresolved site is counted per `(file, enclosing fn, normalised text)`, so a
    duplicate of an existing site in a new fn is a new site.
    """
    files = production_sources(source)
    masks = {path: code_mask(text) for path, text in files.items()}
    consts: dict[str, set[str]] = {}
    for path, text in files.items():
        for match in CONST_STR.finditer(text):
            if masks[path][match.start()] == text[match.start()]:
                consts.setdefault(match.group(1), set()).add(match.group(2))
    required_names, read_names, scopes = readers_of(files, masks)
    call = reader_call(required_names, read_names)
    required: set[str] = set()
    reads: set[str] = set()
    unresolved: Counter = Counter()
    for path, text in files.items():
        mask = masks[path]
        for match in call.finditer(mask):
            if re.search(r"\b(?:fn|macro_rules!)\s*$", mask[max(0, match.start() - 16) : match.start()]):
                continue  # the reader's own definition, not a call
            if not visible(scopes, match.group(0), path, match.start()):
                continue  # a closure reader's name outside the block that binds it
            argument = KEY_ARGUMENT.match(text, match.end())
            prefix, literal, constant = argument.groups() if argument else (None, None, None)
            keys = {literal} if literal else consts.get(constant or "", set())
            if prefix and UPPER_TOKEN.search(prefix):
                keys = set()  # `f(K9, D)`: the key is the first argument, never the second
            if not keys:
                opening = mask.find("(", match.end())
                site = " ".join(text[match.start() : matching_paren(mask, opening)].split())
                unresolved[(path, enclosing_fn(mask, match.start()), site)] += 1
                continue
            reads.update(keys)
            if match.group("required"):
                required.update(keys)
    return required, reads, unresolved


def env_keys(source: dict[str, str]) -> tuple[set[str], set[str]]:
    """`(required keys, every key read)` at the env-read call sites of the non-test source."""
    required, reads, _ = env_sites(source)
    return required, reads


def entry_points(source: dict[str, str]) -> Counter:
    """Calls whose env read happens elsewhere: `*from_env*` / `*from_lookup*`, and any call handed a reader."""
    files = production_sources(source)
    masks = {path: code_mask(text) for path, text in files.items()}
    _, read, _ = readers_of(files, masks)
    passed = {name.replace("\\", "") for name in read if not name.endswith("!")} | {"std::env::var", "env::var"}
    counts: Counter = Counter()
    for mask in masks.values():
        for match in CALL.finditer(mask):
            name = match.group(1)
            if name in NOT_CALLS or re.search(r"\b(?:fn|macro_rules!)\s*$", mask[max(0, match.start() - 16) : match.start()]):
                continue
            opening = match.end() - 1
            if ENTRY_POINT.match(mask, match.start()) or {bare(a) for a in arguments(mask, opening)} & passed:
                counts[name] += 1
    return counts


def tripwire(source: dict[str, str]) -> Counter:
    counts: Counter = Counter()
    for text in production_sources(source).values():
        mask = code_mask(text)
        for token, pattern in TRIPWIRE.items():
            counts[token] += len(pattern.findall(mask))
    return counts


def manifest_of(source: dict[str, str]) -> dict | None:
    return tomllib.loads(source["Cargo.toml"]) if "Cargo.toml" in source else None


def shared_crates(source: dict[str, str]) -> dict[str, dict] | None:
    """`{yadgar-* crate: its spec}` of `Cargo.toml`'s non-dev dependencies; None without one."""
    manifest = manifest_of(source)
    if manifest is None:
        return None
    tables = [manifest.get("dependencies") or {}, manifest.get("build-dependencies") or {}]
    tables += [(t or {}).get("dependencies") or {} for t in (manifest.get("target") or {}).values()]
    crates: dict[str, dict] = {}
    for table in tables:
        for name, spec in table.items():
            package = spec.get("package", name) if isinstance(spec, dict) else name
            if package.startswith("yadgar-"):
                crates[package] = spec if isinstance(spec, dict) else {"version": spec}
    return crates


def pin_of(spec: dict) -> str:
    return f"{spec.get('tag') or spec.get('rev') or '?'} ({spec.get('git') or 'no git'})"


def locked_crates(source: dict[str, str]) -> set[tuple[str, str, str]] | None:
    """`{(name, version, source)}` of every `yadgar-*` package in Cargo.lock but the crate itself."""
    if "Cargo.lock" not in source:
        return None
    own = ((manifest_of(source) or {}).get("package") or {}).get("name")
    packages = tomllib.loads(source["Cargo.lock"]).get("package") or []
    return {
        (p["name"], str(p.get("version")), str(p.get("source")))
        for p in packages
        if p.get("name", "").startswith("yadgar-") and p["name"] != own
    }


def crate_findings(module: str, old_source: dict, new_source: dict) -> list[tuple[str | None, str]]:
    """`(crate or None, reason)` for every shared-crate pin that moved, cannot be pinned, or is overridden."""
    old, new = shared_crates(old_source), shared_crates(new_source)
    if old is None and new is None:
        return []
    if old is None or new is None:
        return [(None, f"{module}: Cargo.toml present at only one of the two tags, so shared crates cannot be compared")]
    findings: list[tuple[str | None, str]] = []
    for name in sorted(old.keys() | new.keys()):
        if old.get(name) != new.get(name):
            moved = f"{pin_of(old[name]) if name in old else 'absent'} -> {pin_of(new[name]) if name in new else 'absent'}"
            findings.append((name, f"{module}: shared crate {name} moved {moved}"))
        spec = new.get(name)
        if spec is not None and (
            spec.get("workspace") or spec.get("branch") or spec.get("path") or not spec.get("git")
            or not (spec.get("tag") or spec.get("rev"))
        ):
            findings.append((name, f"{module}: shared crate {name} has no immutable git tag or rev pin ({spec})"))
    manifest = manifest_of(new_source) or {}
    for table in ("patch", "replace", "workspace"):
        if manifest.get(table):
            findings.append((None, f"{module}: Cargo.toml carries [{table}], which can redirect a shared crate"))
    for kind in ("lib", "bin", "example"):
        targets = manifest.get(kind) or []
        for target in targets if isinstance(targets, list) else [targets]:
            if str(target.get("path", "src/")).split("/")[0] != "src":
                findings.append((None, f"{module}: Cargo.toml [{kind}] path {target.get('path')} is outside src/"))
    old_lock, new_lock = locked_crates(old_source), locked_crates(new_source)
    if old_lock is None or new_lock is None:
        findings.append((None, f"{module}: Cargo.lock missing at one of the two tags, so locked shared crates cannot be compared"))
    else:
        for entry in sorted(old_lock ^ new_lock):
            side = "now locks" if entry in new_lock else "no longer locks"
            findings.append((entry[0], f"{module}: Cargo.lock {side} {entry[0]} {entry[1]} from {entry[2]}"))
    return findings


def crate_moves(module: str, old_source: dict, new_source: dict, only: str | None = None) -> list[str]:
    """The reasons of `crate_findings` (`only`: those naming that crate alone)."""
    return [reason for name, reason in crate_findings(module, old_source, new_source) if only is None or name == only]


def optional(name: str) -> bool:
    return name in OPTIONAL_ENV or name.endswith(OPTIONAL_ENV_SUFFIXES)


def boot_audit(module: str, old_source: dict, new_source: dict, rendered: set[str] | None) -> list[str]:
    """E3 for one moved module: new env names the render does not set, new unreadable sites, moved shared crates."""
    if rendered is None:
        return [f"{module}: a container takes `envFrom`, so the keys it sets cannot be read from the render"]
    if not production_sources(new_source):
        return [f"{module}: no Rust source under src/ at the new tag, so nothing could be audited"]
    old_required, old_reads, old_unresolved = env_sites(old_source)
    new_required, new_reads, new_unresolved = env_sites(new_source)
    reasons = [
        f"{module}: required key {key} is new at the new tag and the render does not set it"
        for key in sorted(new_required - old_required)
        if key not in rendered
    ]
    reasons += [
        f"{module}: env read {name} is new at the new tag, not rendered and not a known optional name"
        for name in sorted(new_reads - old_reads - new_required)
        if name not in rendered and not optional(name)
    ]
    reasons += [
        f"{module}: an env read at a new call site whose key E3 cannot resolve: `{site}` ({path}, fn {function})"
        for (path, function, site) in sorted(new_unresolved - old_unresolved)
    ]
    grown_entries = entry_points(new_source) - entry_points(old_source)
    reasons += [
        f"{module}: a new call to shared-crate env entry point `{name}` (x{count}); the keys it reads are not visible here"
        for name, count in sorted(grown_entries.items())
    ]
    grown_tokens = tripwire(new_source) - tripwire(old_source)
    reasons += [
        f"{module}: env tripwire `{token}` grew by {count}; a reader shape E3 does not model may have been added"
        for token, count in sorted(grown_tokens.items())
    ]
    return reasons + crate_moves(module, old_source, new_source)


def rendered_env(documents: list, module: str) -> set[str] | None | bool:
    """Env names the render sets on EVERY container running `module`'s image (each is audited on its own env);
    None if one takes envFrom; False if none runs it."""
    per_container: list[set[str]] = []
    for document in documents:
        if not isinstance(document, dict) or document.get("kind") not in WORKLOAD_KINDS:
            continue
        pod = ((document.get("spec") or {}).get("template") or {}).get("spec") or {}
        for container in (pod.get("containers") or []) + (pod.get("initContainers") or []):
            if split_image(str(container.get("image", "")))[0] != REGISTRY + module:
                continue
            if container.get("envFrom"):
                return None
            per_container.append({entry["name"] for entry in container.get("env") or []})
    return set.intersection(*per_container) if per_container else False


# ── E4: the migration diff ──────────────────────────────────────────────────

MIGRATION_VERSION = re.compile(r"\bversion:\s*(\d+)\s*,")


def schema_sources(source: dict[str, str]) -> dict[str, str]:
    return {p: t for p, t in production_sources(source).items() if p == "src/schema.rs" or p.startswith("src/schema/")}


def migration_blocks(source: dict[str, str]) -> dict[int, str]:
    """`{version: the struct literal that declares it}` across `src/schema.rs` and `src/schema/**`."""
    blocks: dict[int, str] = {}
    for path, text in schema_sources(source).items():
        mask = code_mask(text)
        for match in MIGRATION_VERSION.finditer(mask):
            opening = mask.rfind("{", 0, match.start())
            version = int(match.group(1))
            if version in blocks:
                raise Refused(f"migration {version} declared twice ({path})")
            blocks[version] = " ".join(text[opening : matching_brace(mask, opening)].split())
    return blocks


def migration_audit(module: str, old_source: dict, new_source: dict) -> list[str]:
    """E4 for one moved -db module: any added, removed or changed migration."""
    old, new = migration_blocks(old_source), migration_blocks(new_source)
    if not new:
        return [f"{module}: no migration found in src/schema.rs or src/schema/ at the new tag"]
    reasons = []
    if added := sorted(new.keys() - old.keys()):
        reasons.append(
            f"{module}: migration(s) {', '.join(map(str, added))} added; a revert does not undo a migration; interim block; lifted by car C10 per ADR-0948 R5"
        )
    if removed := sorted(old.keys() - new.keys()):
        reasons.append(f"{module}: migration(s) {', '.join(map(str, removed))} removed")
    reasons += [f"{module}: migration {v} changed" for v in sorted(old.keys() & new.keys()) if old[v] != new[v]]
    # COARSE: any change to a schema file outside the blocks (SQL from a const, a migration dropped from the
    # set) and any file the schema includes are not readable here.
    old_files, new_files = schema_sources(old_source), schema_sources(new_source)
    reasons += [
        f"{module}: schema source {path} changed"
        for path in sorted(old_files.keys() | new_files.keys())
        if " ".join(old_files.get(path, "").split()) != " ".join(new_files.get(path, "").split())
    ]
    reasons += [
        f"{module}: schema source {path} uses include_str!/include_bytes!, which E4 cannot read"
        for path, text in sorted(new_files.items())
        if re.search(r"\binclude_(?:str|bytes)!", code_mask(text))
    ]
    # yadgar-store's migrate.rs owns the migration ledger's own DDL, so its move is a schema change too.
    reasons += [
        f"{r}; store's migrate.rs owns the ledger DDL; interim block; lifted by car C10 per ADR-0948 R5"
        for r in crate_moves(module, old_source, new_source, only="yadgar-store")
    ]
    return reasons


# ── the network (public reads only) ─────────────────────────────────────────


class Net:
    """Anonymous reads. `GITHUB_TOKEN`, when set, goes to GitHub hosts only and is never printed."""

    GITHUB_HOSTS = ("https://api.github.com/", "https://raw.githubusercontent.com/", "https://codeload.github.com/")
    MANIFESTS = ",".join(
        (
            "application/vnd.oci.image.index.v1+json",
            "application/vnd.docker.distribution.manifest.list.v2+json",
            "application/vnd.oci.image.manifest.v1+json",
            "application/vnd.docker.distribution.manifest.v2+json",
        )
    )

    def __init__(self) -> None:
        self.token = os.environ.get("GITHUB_TOKEN") or ""
        self.sources: dict[tuple[str, str], dict[str, str]] = {}

    def get(self, url: str, headers: dict | None = None, method: str = "GET"):
        headers = dict(headers or {})
        if self.token and url.startswith(self.GITHUB_HOSTS):
            headers["Authorization"] = f"Bearer {self.token}"
        request = urllib.request.Request(url, headers=headers, method=method)  # noqa: S310  (fixed https hosts)
        return urllib.request.urlopen(request, timeout=60)  # noqa: S310

    def chart_yaml(self, version: str) -> str:
        with self.get(f"https://raw.githubusercontent.com/yadgarhq/chart/v{version}/chart/Chart.yaml") as response:
            return response.read().decode()

    def chart_tags(self) -> list[str]:
        finished = subprocess.run(
            ["git", "ls-remote", "--tags", "--refs", "https://github.com/yadgarhq/chart"],
            capture_output=True,
            text=True,
            check=True,
            timeout=60,
        )
        return [line.rsplit("refs/tags/", 1)[-1] for line in finished.stdout.splitlines()]

    def commits(self, old: str, new: str) -> list[dict]:
        url = f"https://api.github.com/repos/yadgarhq/chart/compare/v{old}...v{new}"
        with self.get(url, {"Accept": "application/vnd.github+json"}) as response:
            body = json.load(response)
        return [{"sha": c["sha"][:7], "subject": c["commit"]["message"].splitlines()[0]} for c in body["commits"]]

    def ghcr_digest(self, module: str, tag: str) -> str:
        """The top-level manifest digest of `ghcr.io/yadgarhq/<module>:<tag>`, anonymously."""
        with self.get(f"https://ghcr.io/token?scope=repository:yadgarhq/{module}:pull") as response:
            token = json.load(response)["token"]
        headers = {"Authorization": f"Bearer {token}", "Accept": self.MANIFESTS}
        with self.get(f"https://ghcr.io/v2/yadgarhq/{module}/manifests/{tag}", headers, "HEAD") as response:
            return response.headers["Docker-Content-Digest"]

    def source(self, module: str, version: str) -> dict[str, str]:
        """`{src/…: text, "Cargo.toml": text, "Cargo.lock": text}` of `yadgarhq/<module>@v<version>`, read in memory, never extracted."""
        if (module, version) not in self.sources:
            url = f"https://codeload.github.com/yadgarhq/{module}/tar.gz/refs/tags/v{version}"
            with self.get(url) as response:
                archive = tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")
            files = {}
            for member in archive.getmembers():
                relative = member.name.split("/", 1)[-1]
                wanted = relative in ("Cargo.toml", "Cargo.lock") or (relative.startswith("src/") and relative.endswith(".rs"))
                if member.isfile() and wanted:
                    files[relative] = archive.extractfile(member).read().decode("utf-8", "replace")
            self.sources[(module, version)] = files
        return self.sources[(module, version)]


# ── putting it together ─────────────────────────────────────────────────────


def audits(head: list, old_modules: dict, new_modules: dict, net: Net) -> tuple[dict, dict]:
    """E3 and E4 for every moved module: `(boot audit, migrations)`, each `{module: {status, reasons}}`."""
    moved = sorted(m for m in new_modules if m != PLATFORM and m in old_modules and old_modules[m] != new_modules[m])
    boot: dict[str, dict] = {}
    migrations: dict[str, dict] = {}
    for module in moved:
        old, new = net.source(module, old_modules[module]), net.source(module, new_modules[module])
        env = rendered_env(head, module)
        if env is False:
            reasons = crate_moves(module, old, new)
            note = "no rendered container runs this module; shared crates compared only"
            boot[module] = {"status": "red" if reasons else "skipped", "reasons": reasons, "note": note}
        else:
            reasons = boot_audit(module, old, new, env)
            boot[module] = {"status": "red" if reasons else "green", "reasons": reasons}
        if module.endswith("-db"):
            reasons = migration_audit(module, old, new)
            migrations[module] = {"status": "red" if reasons else "green", "reasons": reasons}
    return boot, migrations


def check(repo: Path, target: str, net: Net, helms: dict[str, str]) -> dict:
    """The evidence for moving `repo`'s pin to `target`: E1, E3, E4, the module table and the commit range."""
    application_text = (repo / APPLICATION).read_text()
    pin = current_pin(application_text)
    decide(pin, target)
    if not helms:
        raise Refused("no helm found")
    old_modules, new_modules = modules_of(net.chart_yaml(pin)), modules_of(net.chart_yaml(target))
    renders = {
        label: (render(application_text, pin, binary), render(application_text, target, binary))
        for label, binary in sorted(helms.items())
    }
    verdict = classify(renders, old_modules, new_modules, net.ghcr_digest)
    boot, migrations = audits(renders[verdict.helms[0]][1], old_modules, new_modules, net)
    reasons = verdict.reasons + [r for b in boot.values() for r in b["reasons"]]
    reasons += [r for m in migrations.values() for r in m["reasons"]]
    return {
        "pin": pin,
        "target": target,
        "modules": {"old": old_modules, "new": new_modules},
        "commits": net.commits(pin, target),
        "helms": verdict.helms,
        "objects": verdict.objects,
        "changed": verdict.changed,
        "boot_audit": boot,
        "migrations": migrations,
        "accept": not reasons,
        "reasons": reasons,
    }


def writer_helm() -> str:
    helms = discover_helms()
    if WRITER_HELM not in helms:
        raise Refused(f"the K3 table is written with helm {WRITER_HELM}; found {sorted(helms) or 'none'}")
    return helms[WRITER_HELM]


def write_files(tree: Path, target: str) -> None:
    """Rewrite the three mechanical files of `tree` for `target`, the table by `tree`'s own writer."""
    application = tree / APPLICATION
    rewritten, pin = rewrite_target_revision(application.read_text(), target)
    decide(pin, target)
    chart_pin = rewrite_chart_pin((tree / CHART_PIN).read_text(), target)
    helm = writer_helm()
    application.write_text(rewritten)
    (tree / CHART_PIN).write_text(chart_pin)
    with helm_on_path(helm):
        finished = subprocess.run(
            [sys.executable, str(tree / WRITER), "--write"], capture_output=True, text=True, check=False
        )
    if finished.returncode != 0:
        raise Refused(f"{WRITER} --write exited {finished.returncode}:\n{finished.stderr}")


# ── the body ────────────────────────────────────────────────────────────────


def carried(evidence: dict) -> list[str]:
    old, new = evidence["modules"]["old"], evidence["modules"]["new"]
    return [f"{m} {new[m]}" for m in sorted(new) if m in old and old[m] != new[m]]


def changelog_bullet(evidence: dict) -> str:
    moved = carried(evidence)
    tail = ""
    if moved:
        tail = ", carrying " + (moved[0] if len(moved) == 1 else ", ".join(moved[:-1]) + " and " + moved[-1])
    return f"- fix: move the yadgar pin to parent chart {evidence['target']}{tail}"


def module_table(evidence: dict) -> list[str]:
    old, new = evidence["modules"]["old"], evidence["modules"]["new"]
    rows = ["| Module | From | To |", "| --- | --- | --- |"]
    rows += [
        f"| {m} | {old.get(m, '-')} | **{new.get(m, '-')}** |"
        for m in sorted(old.keys() | new.keys())
        if old.get(m) != new.get(m)
    ]
    same = sorted(m for m in old if new.get(m) == old[m])
    if same:
        rows.append(f"| {', '.join(same)} | {', '.join(old[m] for m in same)} | unchanged |")
    return rows


def audit_lines(title: str, results: dict, none: str) -> list[str]:
    if not results:
        return [f"- **{title}.** {none}"]
    lines = [f"- **{title}.**"]
    for module, result in sorted(results.items()):
        detail = "; ".join(result["reasons"]) or result.get("note", "")
        lines.append(f"  - {module}: {result['status']}" + (f" ({detail})" if detail else ""))
    return lines


def pr_body(evidence: dict) -> str:
    """The pin PR's body: the template's five sections, final at creation (it is never edited after the push)."""
    pin, target = evidence["pin"], evidence["target"]
    changed = evidence["changed"]
    what = [
        "## What",
        "",
        f"This PR moves the `yadgar` Application from parent chart {pin} to **{target}**, and moves "
        f"`scripts/chart_pin.json` to `v{target}`. **Merging it moves kind-yadgar.** "
        "`scripts/pin_bump.py` generated the three files and this body.",
        "",
        f"Verdict of the offline checks: **{'ACCEPT' if evidence['accept'] else 'NEEDS-HUMAN'}**.",
        "",
        *module_table(evidence),
        "",
        f"`v{pin}..v{target}` in `yadgarhq/chart` is {len(evidence['commits'])} commit(s):",
        "",
        "| Commit | Subject |",
        "| --- | --- |",
        *[f"| `{c['sha']}` | {c['subject'].replace('|', '/')} |" for c in evidence["commits"]],
    ]
    why = [
        "## Why",
        "",
        "ADR-0946: each published parent chart version deploys to kind-yadgar automatically, and the ADR-0881 "
        "evidence runs as checks instead of a hand audit.",
    ]
    changelog = ["## Changelog", "", changelog_bullet(evidence)]
    verification = [
        "## Verification",
        "",
        "`scripts/pin_bump.py --check` rendered both pins with this repository's own `valuesObject` on helm "
        f"{', '.join(evidence['helms'])}.",
        "",
        f"- **E1 render diff.** {evidence['objects']} objects at the target; {len(changed)} changed, `image` only:",
        *[
            f"  - `{c['object']}` `{c['field']}`: `{c['digest']}`, the GHCR tag digest of "
            f"`{c['module']}:{c['version']}`"
            for c in changed
        ],
        *audit_lines("E3 boot audit", evidence["boot_audit"], "No module moved."),
        *audit_lines("E4 migration diff", evidence["migrations"], "No `-db` module moved."),
        "- **Not covered here:** E2, the kind-yadgar dry run, is a separate check.",
    ]
    if not evidence["accept"]:
        verification += ["", "**NEEDS-HUMAN.** Each reason below blocks the automatic merge:", ""]
        verification += [f"- {reason}" for reason in evidence["reasons"]]
    rolled = sorted({c["object"] for c in changed})
    risk = [
        "## Risk",
        "",
        f"What rolls: {', '.join(f'`{o}`' for o in rolled) or 'nothing in the render'}. "
        "A bad image fails its own rollout, and the settled-state gate judges the result after sync.",
        "",
        "**Rollback.**",
        "",
        "1. If `yadgar`'s operation is Running or retrying, first run (NEEDS-MAX) `argocd app terminate-op yadgar`. "
        "Argo CD v3.1.8 has no `retry.refresh`, so a retrying operation keeps applying the bad revision.",
        "2. Revert this PR's commit by PR.",
        "3. A revert is clean only for a pin with no migration, which is why E4 blocks every migration "
        "(interim block; lifted by car C10 per ADR-0948 R5).",
    ]
    return "\n".join(what + [""] + why + [""] + changelog + [""] + verification + [""] + risk) + "\n"


# ── CLI ─────────────────────────────────────────────────────────────────────


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--target", required=True, help="parent chart version X.Y.Z, or `latest`")
    parser.add_argument("--check", action="store_true", help="classify only")
    parser.add_argument("--write", action="store_true", help="rewrite the three mechanical files")
    parser.add_argument("--body", action="store_true", help="print the pull request body")
    parser.add_argument("--evidence", type=Path, help="write the evidence JSON here")
    parser.add_argument("--repo", type=Path, default=REPOSITORY, help=argparse.SUPPRESS)
    arguments = parser.parse_args(argv)
    if not (arguments.check or arguments.write or arguments.body):
        parser.error("say --check, --write and/or --body")

    net = Net()
    evidence = None
    try:
        target = highest_release(net.chart_tags()) if arguments.target == "latest" else arguments.target
        decide(current_pin((arguments.repo / APPLICATION).read_text()), target)
        if arguments.check or arguments.body:
            evidence = check(arguments.repo, target, net, discover_helms())
            if arguments.evidence:
                arguments.evidence.write_text(json.dumps(evidence, indent=2) + "\n")
        if arguments.write:
            write_files(arguments.repo, target)
            print(f"wrote {', '.join(MECHANICAL_FILES)} for {target}", file=sys.stderr)
    except NoOp as no_op:
        print(f"no-op: {no_op}", file=sys.stderr)
        return EXIT_NO_OP
    except Refused as refused:
        print(f"refused: {refused}", file=sys.stderr)
        return EXIT_ERROR

    if evidence is None:
        return EXIT_ACCEPT
    if arguments.body:
        sys.stdout.write(pr_body(evidence))
    status = "ACCEPT" if evidence["accept"] else "NEEDS-HUMAN"
    print(f"{status}: {evidence['pin']} -> {evidence['target']}, {len(evidence['changed'])} image change(s)", file=sys.stderr)
    for reason in evidence["reasons"]:
        print(f"  - {reason}", file=sys.stderr)
    return EXIT_ACCEPT if evidence["accept"] else EXIT_NEEDS_HUMAN


if __name__ == "__main__":
    sys.exit(main())
