@dataclass
class Verdict:
    accept: bool
    reasons: list[str] = field(default_factory=list)
    changed: list[dict] = field(default_factory=list)
    objects: int = 0
    helms: list[str] = field(default_factory=list)


def objects_of(documents: list) -> dict[str, dict]:
    key = gate("test_yadgar_application").object_key
    return {key(d): d for d in documents if isinstance(d, dict) and d.get("kind")}


def field_paths(old, new, path: str = "") -> list[str]:
    """Every path where `old` and `new` differ; lists of equal length are compared by index."""
    if isinstance(old, dict) and isinstance(new, dict):
        return [
            found
            for key in sorted(set(old) | set(new))
            for found in field_paths(old.get(key), new.get(key), f"{path}.{key}".lstrip("."))
        ]
    if isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        return [found for i, (a, b) in enumerate(zip(old, new, strict=True)) for found in field_paths(a, b, f"{path}[{i}]")]
    return [] if old == new else [path or "<root>"]


def at(document, path: str):
    node = document
    for part in re.findall(r"[^.\[\]]+|\[\d+\]", path):
        node = node[int(part[1:-1])] if part.startswith("[") else node[part]
    return node


def split_image(reference: str) -> tuple[str, str]:
    """`(repository, digest)` of `repo[:tag][@digest]`."""
    named, _, digest = reference.partition("@")
    last = named.rsplit("/", 1)[-1]
    repository = named.rsplit(":", 1)[0] if ":" in last else named
    return repository, digest


def module_moves(old_modules: dict[str, str], new_modules: dict[str, str]) -> list[str]:
    reasons = []
    for name in sorted(set(old_modules) ^ set(new_modules)):
        side = "added to" if name in new_modules else "removed from"
        reasons.append(f"dependency {name} {side} the parent Chart.yaml")
    # A `platform` move is judged by its own evidence, `classify_platform` over the five operator Applications
    # (car C10; the C1 categorical block is gone, Max ruled the platform-move set 2026-10-31).
    return reasons


def classify(renders: dict, old_modules: dict, new_modules: dict, digest_of) -> Verdict:
    """E1. `renders` is `{helm version: (base documents, head documents)}`."""
    digests = gate("test_yadgar_application").digests
    helms = sorted(renders)
    reasons: list[str] = []
    if len(helms) < 2:
        reasons.append(f"only one helm version rendered ({', '.join(helms) or 'none'}); acceptance needs two that agree")
    first = helms[0]
    for other in helms[1:]:
        for side, index in (("base", 0), ("head", 1)):
            a, b = digests(renders[first][index]), digests(renders[other][index])
            if a != b:
                differing = sorted(k for k in a.keys() | b.keys() if a.get(k) != b.get(k))
                reasons.append(f"helm {first} and helm {other} disagree at the {side} pin: {', '.join(differing)}")

    reasons += module_moves(old_modules, new_modules)

    base, head = (objects_of(documents) for documents in renders[first])
    reasons += [f"object removed: {key}" for key in sorted(base.keys() - head.keys())]
    reasons += [f"object added: {key}" for key in sorted(head.keys() - base.keys())]

    changed: list[dict] = []
    for key in sorted(base.keys() & head.keys()):
        old, new = base[key], head[key]
        for path in field_paths(old, new):
            if old.get("kind") not in WORKLOAD_KINDS or not IMAGE_FIELD.match(path):
                reasons.append(f"{key}: field {path} changed; only a workload's container image may change")
                continue
            entry, problems = judge_image(key, path, at(old, path), at(new, path), old_modules, new_modules, digest_of)
            reasons += problems
            if entry:
                changed.append(entry)

    return Verdict(accept=not reasons, reasons=reasons, changed=changed, objects=len(head), helms=helms)


def judge_image(key, path, old_image, new_image, old_modules, new_modules, digest_of) -> tuple[dict | None, list[str]]:
    """One changed image against the rules; `(evidence entry or None, problems)`."""
    old_repository, _ = split_image(str(old_image))
    repository, digest = split_image(str(new_image))
    problems = []
    if repository != old_repository:
        problems.append(f"{key}: {path} repository changed {old_repository} -> {repository}")
    module = repository[len(REGISTRY) :] if repository.startswith(REGISTRY) else ""
    if not module or "/" in module:
        problems.append(f"{key}: {path} repository {repository} is not {REGISTRY}<module>")
        return None, problems
    if module not in new_modules:
        problems.append(f"{key}: {path} image of {module}, which is no dependency of the parent")
        return None, problems
    version = new_modules[module]
    if old_modules.get(module) == version:
        problems.append(f"{key}: {path} image of module {module} changed but its version did not move ({version})")
        return None, problems
    try:
        expected = digest_of(module, version)
    except Exception as error:  # noqa: BLE001  (an unreadable registry is a red, never a green)
        problems.append(f"{key}: the GHCR tag digest of {module}:{version} could not be read ({error})")
        return None, problems
    if digest != expected:
        problems.append(
            f"{key}: {path} digest {digest or '<none>'} is not the GHCR tag digest of {module}:{version} ({expected})"
        )
    return {"object": key, "field": path, "module": module, "version": version, "digest": digest}, problems


