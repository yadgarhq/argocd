class NoOp(Exception):
    """The target is the pin: nothing to do."""


class Refused(Exception):
    """The request cannot be carried out as asked."""


# ── versions ────────────────────────────────────────────────────────────────

RELEASE = re.compile(r"^v?(\d+)\.(\d+)\.(\d+)$")


def release(version: str) -> tuple[int, int, int] | None:
    """`(major, minor, patch)` of a release version, None for a prerelease or anything else."""
    match = RELEASE.match(version.strip())
    return tuple(int(part) for part in match.groups()) if match else None


def highest_release(tags) -> str:
    """The numeric maximum of the release tags, bare. Prereleases are ignored (ADR-0690: never lexical)."""
    releases = [found for found in (release(tag) for tag in tags) if found]
    if not releases:
        raise Refused("no release tag found")
    return ".".join(str(part) for part in max(releases))


def decide(pin: str, target: str) -> None:
    """Raise NoOp when target is the pin, Refused when it is lower or not a release; None for a bump."""
    wanted, current = release(target), release(pin)
    if wanted is None:
        raise Refused(f"target {target!r} is not a release version X.Y.Z; a prerelease is never pinned")
    if current is None:
        raise Refused(f"the current pin {pin!r} is not a release version X.Y.Z")
    if wanted == current:
        raise NoOp(f"target {target} is the current pin")
    if wanted < current:
        raise Refused(f"target {target} is lower than the current pin {pin}")


# ── the mechanical files ────────────────────────────────────────────────────

# A non-comment line: whitespace, then the key. The comments in yadgar.yaml
# that name `targetRevision` start with `#` and never match.
TARGET_REVISION = re.compile(r"^([ \t]+targetRevision:[ \t]*)(\S+)[ \t]*$", re.M)
CHART_TAG = re.compile(r'^([ \t]*"chart_tag":[ \t]*")([^"]*)(")', re.M)
CHART_DIGEST = re.compile(r'^([ \t]*"chart_digest":[ \t]*")([^"]*)(")', re.M)
# The parent chart's package under ghcr.io/yadgarhq/, as `Net.ghcr_digest` names it.
CHART_PACKAGE = "charts/yadgar"
DIGEST = re.compile(r"sha256:[0-9a-f]{64}")
PLATFORM_VERSION_LINE = re.compile(r'^([ \t]*"platform_version":[ \t]*")([^"]*)(")', re.M)


def parsed_revision(text: str) -> str:
    return str(yaml.safe_load(text)["spec"]["source"]["targetRevision"])


def current_pin(text: str, path: str = APPLICATION) -> str:
    matches = TARGET_REVISION.findall(text)
    if len(matches) != 1:
        raise Refused(f"`targetRevision:` matched {len(matches)} line(s) in {path}; exactly 1 is rewritten")
    return matches[0][1]


def rewrite_target_revision(text: str, target: str, path: str = APPLICATION) -> tuple[str, str]:
    """`(new text, old revision)`, with the one `targetRevision:` line moved and nothing else."""
    old = current_pin(text, path)
    match = TARGET_REVISION.search(text)
    rewritten = text[: match.start(2)] + target + text[match.end(2) :]
    for document, wanted in ((text, old), (rewritten, target)):
        if parsed_revision(document) != wanted:
            raise Refused(
                f"{path}: the line rewritten is not `spec.source.targetRevision` (YAML reads {parsed_revision(document)!r})"
            )
    return rewritten, old


def rewrite_chart_pin(text: str, target: str, *, digest: str, platform: str | None = None) -> str:
    """`chart_tag` set to `v<target>`, `chart_digest` to `digest`, and `platform_version` to `platform` when given;
    every other byte kept."""
    if not DIGEST.fullmatch(digest or ""):
        raise Refused(f"chart digest {digest!r} is not sha256:<64 lowercase hex>")
    edits = [(CHART_TAG, "chart_tag", f"v{target}"), (CHART_DIGEST, "chart_digest", digest)]
    if platform is not None:
        edits.append((PLATFORM_VERSION_LINE, "platform_version", platform))
    rewritten = text
    for pattern, key, value in edits:
        matches = list(pattern.finditer(rewritten))
        if len(matches) != 1:
            raise Refused(f'`"{key}":` matched {len(matches)} line(s) in {CHART_PIN}; exactly 1 is rewritten')
        match = matches[0]
        rewritten = rewritten[: match.start(2)] + value + rewritten[match.end(2) :]
        if json.loads(rewritten).get(key) != value:
            raise Refused(f"{CHART_PIN} does not parse to the new {key} after the edit")
    return rewritten


def chart_digest(version: str) -> str:
    """The OCI manifest digest `ghcr.io/yadgarhq/charts/yadgar:<version>` resolves to now, anonymously."""
    return Net().ghcr_digest(CHART_PACKAGE, version)


def modules_of(chart_yaml: str) -> dict[str, str]:
    """`{dependency name: version}` of a parent `chart/Chart.yaml`."""
    return {str(d["name"]): str(d["version"]) for d in yaml.safe_load(chart_yaml).get("dependencies") or []}


