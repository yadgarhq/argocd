#!/usr/bin/env python3
"""The automatic pin's offline engine: move `yadgar` to a new parent chart version (ADR-0946, ledger 1632 C1).

ADR-0946 deploys every published parent chart version to kind-yadgar without a
human step, and turns ADR-0881's hand evidence into checks. This file is the
part of that which needs no credential, no cluster and no GitHub write: it
reads public sources only (anonymous GHCR pulls, raw.githubusercontent.com,
the GitHub REST API and codeload tarballs; `GITHUB_TOKEN`, when set, only
raises the rate limit and is never printed).

    python3 scripts/pin_bump.py --target 0.25.27 --check     # classify only
    python3 scripts/pin_bump.py --target latest  --write     # rewrite the 3 files
    python3 scripts/pin_bump.py --target 0.25.27 --check --body --evidence e.json

THE THREE MECHANICAL FILES (`--write`):

- `applications/yadgar.yaml`: the one `targetRevision:` line, by a
  line-anchored edit, so every comment survives. Refused unless exactly one
  non-comment line matches, and unless the YAML parse agrees before and after.
- `scripts/chart_pin.json`: `chart_tag` only. `platform_version` is NOT moved:
  a platform move moves the five operator Applications too, and this plan
  leaves that to a human (the classifier reports it as NEEDS-HUMAN).
- `scripts/gates/yadgar_render.sha256`: regenerated by the writer that already
  exists, `scripts/gates/test_yadgar_application.py --write`, with helm
  v3.18.4. `--write` blesses whatever renders, so it proves nothing by itself;
  the classifier is the proof.

THE CLASSIFIER (`--check`) renders the current pin and the target with this
checkout's own `valuesObject`, through the gates' own `parent_render`, on every
distinct helm it finds (`PIN_BUMP_HELMS`, os.pathsep-separated, else helm
3.18.4 at /tmp/helm3184/linux-amd64/helm when present, plus `helm` on PATH).
It ACCEPTS only when every one of these holds; anything else is NEEDS-HUMAN
with a reason per failure:

- two or more distinct helm versions rendered, and they agree byte for byte
  at both pins;
- the object set is identical at both pins;
- every changed object is a Deployment, StatefulSet or Job, and every changed
  field is a `containers[*].image` or `initContainers[*].image`;
- each changed image keeps its repository, and the repository is
  `ghcr.io/yadgarhq/<module>`;
- `<module>`'s version moved in the parent's `chart/Chart.yaml`, and the new
  digest equals the top-level manifest digest of
  `ghcr.io/yadgarhq/<module>:<new version>` (a bare tag, no `v`);
- `platform` did not move, and no dependency was added or removed;
- E3, the boot audit, is green for every moved module: no `env_required*` key
  new at the new source tag that the render does not set, and no upper-snake
  string literal new at the new tag that is neither rendered nor a known
  optional name;
- E4, the migration diff, finds no added, removed or changed migration in any
  moved `-db` module (`src/schema.rs` and `src/schema/**`).

A tag that moved after it was published gives a false red (its digest no
longer matches), never a false green.

E2, the kind-yadgar dry run, is NOT here: it needs the private runner (C4).

Exit codes: 0 accept (or `--write` alone done), 3 NEEDS-HUMAN, 4 no-op (the
target is the pin), 1 refused or error.

Tests: `scripts/tests/test_pin_bump.py` (offline, fixtures) and
`scripts/gates/test_pin_bump_replay.py` (live: #106, #107 and #109 replayed
byte for byte).
"""

