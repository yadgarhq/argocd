def struct_field(text: str, site: MigrationSite, name: str) -> str | None:
    """The source text of field `name`'s expression in the struct literal at `site`, or None when it has none."""
    mask = code_mask(text)
    depth = 0
    for index in range(site.start + 1, site.stop - 1):
        char = mask[index]
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif depth == 0 and (match := re.compile(rf"\b{name}\s*:(?!:)").match(mask, index)) and not mask[index - 1].isalnum():
            end, inner = match.end(), 0
            while end < site.stop - 1 and not (inner == 0 and mask[end] == ","):
                inner += 1 if mask[end] in "([{" else -1 if mask[end] in ")]}" else 0
                end += 1
            return text[match.end() : end]
    return None


STRUCT_FIELD = re.compile(r"\s*(?P<name>[A-Za-z_]\w*)\s*:(?!:)", re.ASCII)


def struct_fields(text: str, site: MigrationSite) -> dict[str, str] | None:
    """`{version, name, sql}` -> each field's expression source when the literal at `site` is EXACTLY those three
    fields, each once, with nothing else: no attribute (`#[cfg]`), no `..base`, no other field. Else None.

    A positive grammar, because rustc reads what the first `sql:` does not: two cfg'd `sql:` fields, or a `name:`
    block that runs code, would otherwise pass beside a harmless first match (security review of argocd#214).
    """
    mask = code_mask(text)
    body = mask[site.start + 1 : site.stop - 1]
    if re.search(r"#\s*!?\s*\[", body) or ".." in body:
        return None
    parts, depth, start = [], 0, 0
    for index, char in enumerate(body):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append((start, index))
            start = index + 1
    if body[start:].strip():
        parts.append((start, len(body)))
    fields: dict[str, str] = {}
    for begin, end in parts:
        match = STRUCT_FIELD.match(body, begin, end)
        if not match or match.group("name") in fields:
            return None
        offset = site.start + 1
        fields[match.group("name")] = text[offset + match.end() : offset + end]
    if set(fields) != {"version", "name", "sql"} or not re.fullmatch(r"\s*[0-9]+\s*", fields["version"], re.ASCII):
        return None
    return fields


def safe_name(name: str) -> str:
    """A migration name fit for a reason string and the PR body: no control characters or line breaks, backticks
    escaped."""
    return re.sub(r"[\x00-\x1f\x7f\u0085\u2028\u2029]", " ", name).replace("`", "\\`")


MIGRATION_FN = re.compile(r"(?m)^[ \t]*(?:pub(?:\s*\([^)]*\))?\s+)?fn\s+(\w+)\s*\(\s*\)\s*->\s*(?:\w+\s*::\s*)*Migration\s*\{")


def with_comments_above(text: str, start: int) -> int:
    """`start` moved up over the `///` and `//` lines directly above it (never `//!`, never across a blank line)."""
    while start > 0:
        above = text.rfind("\n", 0, start - 1) + 1
        line = text[above : start - 1].strip()
        if not line.startswith("//") or line.startswith("//!"):
            break
        start = above
    return start


def migration_fn(text: str, site: MigrationSite) -> tuple[str, int, int] | None:
    """`(name, start, stop)` of the `fn name() -> Migration { Migration { … } }` that is exactly the literal at
    `site`, with the comment lines above it and its newline; None when the literal sits anywhere else."""
    mask = code_mask(text)
    for match in MIGRATION_FN.finditer(mask):
        body = match.end() - 1
        stop = matching_brace(mask, body)
        if not body < site.start < site.stop <= stop:
            continue
        only_the_literal = re.fullmatch(r"\s*(?:\w+\s*::\s*)*Migration\s*", mask[body + 1 : site.start]) and not mask[site.stop : stop - 1].strip()
        if not only_the_literal:
            return None
        return match.group(1), with_comments_above(text, match.start()), stop + (text[stop : stop + 1] == "\n")
    return None


def schema_module(path: str) -> str:
    """The Rust module path a list entry names a fn of `path` by: "" for `src/schema.rs`, `x` for `src/schema/x.rs`."""
    return "" if path in ("src/schema.rs", "src/schema/mod.rs") else Path(path).stem


def cut_first(files: dict[str, str], pattern: re.Pattern, whole_line: bool = False) -> bool:
    """Remove the first match of `pattern` (read on the code mask) across `files`, `src/schema.rs` first."""
    for path in sorted(files, key=lambda p: (p != "src/schema.rs", p)):
        text = files[path]
        if not (match := pattern.search(code_mask(text))):
            continue
        start, stop = match.start(), match.end()
        if whole_line:
            start = with_comments_above(text, start)
        elif re.match(r"\s*,", text[stop:]):
            stop += len(re.match(r"\s*,", text[stop:]).group())
        elif comma := re.search(r",\s*$", text[:start]):
            start = comma.start()
        files[path] = text[:start] + text[stop:]
        return True
    return False


def residual_reasons(module: str, old_source: dict, new_source: dict, added: list[int]) -> list[str]:
    """ADR-1099: the schema files at the new tag, less each added migration fn and its list entry (and a new child
    file of only `use` lines, comments and migration fns, with its `mod` line), must be the old files."""
    old_files, new_files = schema_sources(old_source), dict(schema_sources(new_source))
    sites = migration_sites(new_source)
    cuts: dict[str, list[tuple[str, int, int]]] = {}
    for version in added:
        site = sites[version]
        if found := migration_fn(new_files[site.path], site):
            cuts.setdefault(site.path, []).append(found)
    for path, spans in cuts.items():
        text = new_files[path]
        for _, start, stop in sorted(set(spans), key=lambda span: -span[1]):
            text = text[:start] + text[stop:]
        new_files[path] = text
    for path, spans in sorted(cuts.items()):
        qualifier = schema_module(path)
        prefix = rf"{qualifier}\s*::\s*" if qualifier else ""
        for name in sorted({name for name, _, _ in spans}):
            cut_first(new_files, re.compile(rf"(?<![\w:.])(?:(?:self|super|crate)\s*::\s*)*{prefix}{name}\s*\(\s*\)"))
    children = []
    for path in sorted(new_files.keys() - old_files.keys()):
        if not path.startswith("src/schema/") or re.sub(r"\buse\s[^;]*;", "", code_mask(new_files[path])).strip():
            continue
        parents = {p: t for p, t in new_files.items() if p != path}
        mod_line = re.compile(rf"(?m)^[ \t]*(?:pub(?:\s*\([^)]*\))?\s+)?mod\s+{Path(path).stem}\s*;[ \t]*\n?")
        if cut_first(parents, mod_line, whole_line=True):
            new_files.update(parents)
            children.append(path)
    return [
        f"{module}: schema source {path} changed outside the added migration(s)"
        for path in sorted(old_files.keys() | new_files.keys())
        if path not in children and " ".join(old_files.get(path, "").split()) != " ".join(new_files.get(path, "").split())
    ]


def migration_evidence(module: str, old_source: dict, new_source: dict, allowlist: tuple = SEED_ALLOWLIST) -> dict:
    """E4 for one moved -db module: `{status, reasons, admitted, forward_only}` (ADR-1099).

    `reasons` names each added migration the classifier does not admit, a removed or changed migration, a schema
    file changed outside the added migrations, an `include_str!`, and a moved `yadgar-store`. `admitted` records each
    admitted migration's version, name, sha256 of its SQL (the store ledger's checksum) and class; `forward_only` is
    every added version, admitted or not: a pin that crosses one cannot be reverted cleanly (DatabaseAhead).
    """
    old, new = migration_blocks(old_source), migration_blocks(new_source)
    if not new:
        reasons = [f"{module}: no migration found in src/schema.rs or src/schema/ at the new tag"]
        return {"status": "red", "reasons": reasons, "admitted": [], "forward_only": []}
    reasons, admitted = [], []
    added = sorted(new.keys() - old.keys())
    texts, sites = schema_sources(new_source), migration_sites(new_source)
    for version in added:
        site = sites[version]
        text = texts[site.path]
        fields = struct_fields(text, site)
        found = migration_fn(text, site)
        name = classifier().rust_literal(fields["name"]) if fields else None
        if name is None:
            label = found[0] if found else "unnamed"
            reasons.append(
                f"{module}: migration {version} ({safe_name(label)}) not admitted: its Migration literal is not exactly the fields "
                "version, name and sql, each once, with literal values (no attribute, `..`, other field or expression)"
            )
            continue
        name = safe_name(name)
        verdict = classifier().classify(fields["sql"], module=module, allowlist=allowlist)
        if verdict.admitted:
            admitted.append({"version": version, "name": name, "checksum": verdict.checksum, "statement_class": verdict.statement_class})
        else:
            reasons.append(f"{module}: migration {version} ({name}) not admitted: {verdict.reason}")
    if removed := sorted(old.keys() - new.keys()):
        reasons.append(f"{module}: migration(s) {', '.join(map(str, removed))} removed")
    # An added version at or below the old maximum never runs on a database already past it: the store applies only
    # `pending_after(applied)`, the versions above the applied high-water mark.
    if old:
        reasons += [
            f"{module}: migration {v} sits at or below the applied high-water mark {max(old)}; the store never runs it on an existing database (pending_after)"
            for v in added
            if v <= max(old)
        ]
    # CHANGED BY EXACT BYTES where both literals decode: the store checksums `sql`'s exact bytes, so a whitespace edit
    # inside an old literal fails boot (ChecksumMismatch) while the whitespace-collapsed block text reads unchanged.
    old_texts, old_sites = schema_sources(old_source), migration_sites(old_source)

    def sql_of(files: dict[str, str], where: dict[int, MigrationSite], version: int) -> str | None:
        site = where[version]
        return classifier().rust_literal(struct_field(files[site.path], site, "sql") or "")

    for v in sorted(old.keys() & new.keys()):
        old_sql, new_sql = sql_of(old_texts, old_sites, v), sql_of(texts, sites, v)
        if old[v] != new[v] or (old_sql is not None and new_sql is not None and old_sql != new_sql):
            reasons.append(f"{module}: migration {v} changed")
    reasons += residual_reasons(module, old_source, new_source, added)
    reasons += [
        f"{module}: schema source {path} uses include_str!/include_bytes!, which E4 cannot read"
        for path, text in sorted(texts.items())
        if re.search(r"\binclude_(?:str|bytes)!", code_mask(text))
    ]
    # yadgar-store's migrate.rs owns the migration ledger's own DDL, so its move is a schema change too (ADR-1092).
    reasons += [
        f"{r}; store's migrate.rs owns the ledger DDL; it stays NEEDS-HUMAN after car C10 (plan E4)"
        for r in crate_moves(module, old_source, new_source, only="yadgar-store")
    ]
    return {"status": "red" if reasons else "green", "reasons": reasons, "admitted": admitted, "forward_only": added}


def migration_audit(module: str, old_source: dict, new_source: dict) -> list[str]:
    """E4's reasons for one moved -db module (`migration_evidence` without the record)."""
    return migration_evidence(module, old_source, new_source)["reasons"]


# ── the network (public reads only) ─────────────────────────────────────────


class Net:
    """Anonymous reads. `GITHUB_TOKEN`, when set, goes to GitHub hosts only and is never printed."""

    GITHUB_HOSTS = ("https://api.github.com/", "https://raw.githubusercontent.com/", "https://codeload.github.com/")
    MANIFESTS = ",".join(
        (
            "application/vnd.oci.image.index.v1+json",
            "application/vnd.docker.distribution.manifest.list.v2+json",
            "application/vnd.oci.image.manifest.v1+json",
            "application/vnd.docker.distribution.manifest.v2+json",
        )
    )

    def __init__(self) -> None:
        self.token = os.environ.get("GITHUB_TOKEN") or ""
        self.sources: dict[tuple[str, str], dict[str, str]] = {}

    def get(self, url: str, headers: dict | None = None, method: str = "GET"):
        headers = dict(headers or {})
        if self.token and url.startswith(self.GITHUB_HOSTS):
            headers["Authorization"] = f"Bearer {self.token}"
        request = urllib.request.Request(url, headers=headers, method=method)  # noqa: S310  (fixed https hosts)
        return urllib.request.urlopen(request, timeout=60)  # noqa: S310

    def chart_yaml(self, version: str) -> str:
        with self.get(f"https://raw.githubusercontent.com/yadgarhq/chart/v{version}/chart/Chart.yaml") as response:
            return response.read().decode()

    def chart_tags(self) -> list[str]:
        finished = subprocess.run(
            ["git", "ls-remote", "--tags", "--refs", "https://github.com/yadgarhq/chart"],
            capture_output=True,
            text=True,
            check=True,
            timeout=60,
        )
        return [line.rsplit("refs/tags/", 1)[-1] for line in finished.stdout.splitlines()]

    def commits(self, old: str, new: str) -> list[dict]:
        url = f"https://api.github.com/repos/yadgarhq/chart/compare/v{old}...v{new}"
        with self.get(url, {"Accept": "application/vnd.github+json"}) as response:
            body = json.load(response)
        return [{"sha": c["sha"][:7], "subject": c["commit"]["message"].splitlines()[0]} for c in body["commits"]]

    def ghcr_digest(self, module: str, tag: str) -> str:
        """The top-level manifest digest of `ghcr.io/yadgarhq/<module>:<tag>`, anonymously."""
        with self.get(f"https://ghcr.io/token?scope=repository:yadgarhq/{module}:pull") as response:
            token = json.load(response)["token"]
        headers = {"Authorization": f"Bearer {token}", "Accept": self.MANIFESTS}
        with self.get(f"https://ghcr.io/v2/yadgarhq/{module}/manifests/{tag}", headers, "HEAD") as response:
            return response.headers["Docker-Content-Digest"]

    def registry_digest(self, repository: str, tag: str) -> str:
        """The top-level manifest digest of `<registry>/<repository>:<tag>` at any OCI registry, anonymously.

        A bare `name` or `org/name` is Docker Hub's. A 401 is answered by the registry's own Bearer challenge
        (`realm`, `service`, `scope`), with no credential: a private image is unreadable, and so a red.
        """
        first, _, rest = repository.partition("/")
        if rest and ("." in first or ":" in first or first == "localhost"):
            host, path = first, rest
        else:
            host, path = "docker.io", repository
        if host == "docker.io":
            host = "registry-1.docker.io"
            path = path if "/" in path else f"library/{path}"
        url = f"https://{host}/v2/{path}/manifests/{tag}"
        headers = {"Accept": self.MANIFESTS}
        try:
            with self.get(url, headers, "HEAD") as response:
                return response.headers["Docker-Content-Digest"]
        except urllib.error.HTTPError as error:
            challenge = error.headers.get("WWW-Authenticate") or ""
            if error.code != 401 or not challenge.lower().startswith("bearer "):
                raise
        fields = dict(re.findall(r'(\w+)="([^"]*)"', challenge))
        query = urllib.parse.urlencode({k: v for k, v in fields.items() if k in ("service", "scope")})
        with self.get(f"{fields['realm']}?{query}") as response:
            body = json.load(response)
        headers["Authorization"] = f"Bearer {body.get('token') or body.get('access_token')}"
        with self.get(url, headers, "HEAD") as response:
            return response.headers["Docker-Content-Digest"]

    def source(self, module: str, version: str) -> dict[str, str]:
        """`{src/…: text, "Cargo.toml": text, "Cargo.lock": text}` of `yadgarhq/<module>@v<version>`, read in memory, never extracted."""
        if (module, version) not in self.sources:
            url = f"https://codeload.github.com/yadgarhq/{module}/tar.gz/refs/tags/v{version}"
            with self.get(url) as response:
                archive = tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")
            files = {}
            for member in archive.getmembers():
                relative = member.name.split("/", 1)[-1]
                wanted = relative in ("Cargo.toml", "Cargo.lock") or (relative.startswith("src/") and relative.endswith(".rs"))
                if member.isfile() and wanted:
                    files[relative] = archive.extractfile(member).read().decode("utf-8", "replace")
            self.sources[(module, version)] = files
        return self.sources[(module, version)]


# ── putting it together ─────────────────────────────────────────────────────


def audits(head: list, old_modules: dict, new_modules: dict, net: Net) -> tuple[dict, dict]:
    """E3 and E4 for every moved module: `(boot audit, migrations)`, each `{module: {status, reasons}}`."""
    moved = sorted(m for m in new_modules if m != PLATFORM and m in old_modules and old_modules[m] != new_modules[m])
    boot: dict[str, dict] = {}
    migrations: dict[str, dict] = {}
    for module in moved:
        old, new = net.source(module, old_modules[module]), net.source(module, new_modules[module])
        env = rendered_env(head, module)
        if env is False:
            reasons = crate_moves(module, old, new)
            note = "no rendered container runs this module; shared crates compared only"
            boot[module] = {"status": "red" if reasons else "skipped", "reasons": reasons, "note": note}
        else:
            reasons = boot_audit(module, old, new, env)
            boot[module] = {"status": "red" if reasons else "green", "reasons": reasons}
        if module.endswith("-db"):
            migrations[module] = migration_evidence(module, old, new)
    return boot, migrations


def check(repo: Path, target: str, net: Net, helms: dict[str, str]) -> dict:
    """The evidence for moving `repo`'s pin to `target`: E1, E3, E4, the module table and the commit range."""
    application_text = (repo / APPLICATION).read_text()
    pin = current_pin(application_text)
    decide(pin, target)
    if not helms:
        raise Refused("no helm found")
    old_modules, new_modules = modules_of(net.chart_yaml(pin)), modules_of(net.chart_yaml(target))
    renders = {
        label: (render(application_text, pin, binary), render(application_text, target, binary))
        for label, binary in sorted(helms.items())
    }
    verdict = classify(renders, old_modules, new_modules, net.ghcr_digest)
    boot, migrations = audits(renders[verdict.helms[0]][1], old_modules, new_modules, net)
    platform = None
    old_platform, new_platform = old_modules.get(PLATFORM), new_modules.get(PLATFORM)
    if old_platform and new_platform and old_platform != new_platform:
        yadgar = [d for base, head in renders.values() for d in (*base, *head)]
        platform = platform_evidence(repo, old_platform, new_platform, helms, net, yadgar)
    reasons = verdict.reasons + [r for b in boot.values() for r in b["reasons"]]
    reasons += [r for m in migrations.values() for r in m["reasons"]]
    reasons += platform["reasons"] if platform else []
    return {
        "pin": pin,
        "target": target,
        "modules": {"old": old_modules, "new": new_modules},
        "commits": net.commits(pin, target),
        "helms": verdict.helms,
        "objects": verdict.objects,
        "changed": verdict.changed,
        "boot_audit": boot,
        "migrations": migrations,
        "platform": platform,
        "accept": not reasons,
        "reasons": reasons,
    }


def writer_helm() -> str:
    helms = discover_helms()
    if WRITER_HELM not in helms:
        raise Refused(f"the K3 table is written with helm {WRITER_HELM}; found {sorted(helms) or 'none'}")
    return helms[WRITER_HELM]


def target_platform(target: str) -> str:
    """`platform`'s version in the parent `chart/Chart.yaml` at `target`."""
    found = modules_of(Net().chart_yaml(target)).get(PLATFORM)
    if not found:
        raise Refused(f"the parent chart {target} has no {PLATFORM} dependency")
    return found


def write_files(tree: Path, target: str, platform: str | None = None) -> tuple[str, ...]:
    """Rewrite `tree`'s pin files for `target`, the table by `tree`'s own writer.

    The three always. When the target's `platform` (read from its `chart/Chart.yaml` unless given) differs from
    `chart_pin.json`'s `platform_version`, also `platform_version` and the five operator Applications'
    `targetRevision`, each by a line-anchored edit (car C10). Every file is computed before any is written.
    """
    application = tree / APPLICATION
    rewritten, pin = rewrite_target_revision(application.read_text(), target)
    decide(pin, target)
    chart_pin_text = (tree / CHART_PIN).read_text()
    digest = chart_digest(target)
    current = json.loads(chart_pin_text).get("platform_version")
    platform = platform or target_platform(target)
    operators: dict[str, str] = {}
    if platform != current:
        for path in OPERATOR_APPLICATIONS:
            moved, old = rewrite_target_revision((tree / path).read_text(), platform, path)
            if old != current:
                raise Refused(f"{path} pins platform {old}, but {CHART_PIN} says {current}; they move together or not at all")
            operators[path] = moved
    chart_pin = rewrite_chart_pin(chart_pin_text, target, digest=digest, platform=platform if operators else None)
    helm = writer_helm()
    application.write_text(rewritten)
    (tree / CHART_PIN).write_text(chart_pin)
    for path, text in operators.items():
        (tree / path).write_text(text)
    with helm_on_path(helm):
        run_writer(tree / WRITER)
    return pin_files(platform_moved=bool(operators))


def run_writer(writer: Path) -> None:
    """Run the K3 writer, refusing by name if it outlives `WRITER_TIMEOUT_SECONDS` (yaadgaar #164 item 3)."""
    try:
        finished = subprocess.run(
            [sys.executable, str(writer), "--write"],
            capture_output=True,
            text=True,
            check=False,
            timeout=WRITER_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired:
        raise Refused(f"{WRITER} --write timed out after {WRITER_TIMEOUT_SECONDS} s (a hung helm pull or template)")
    if finished.returncode != 0:
        raise Refused(f"{WRITER} --write exited {finished.returncode}:\n{finished.stderr}")


# ── the body ────────────────────────────────────────────────────────────────


def carried(evidence: dict) -> list[str]:
    old, new = evidence["modules"]["old"], evidence["modules"]["new"]
    return [f"{m} {new[m]}" for m in sorted(new) if m in old and old[m] != new[m]]


def changelog_bullet(evidence: dict) -> str:
    moved = carried(evidence)
    tail = ""
    if moved:
        tail = ", carrying " + (moved[0] if len(moved) == 1 else ", ".join(moved[:-1]) + " and " + moved[-1])
    return f"- fix: move the yadgar pin to parent chart {evidence['target']}{tail}"


def module_table(evidence: dict) -> list[str]:
    old, new = evidence["modules"]["old"], evidence["modules"]["new"]
    rows = ["| Module | From | To |", "| --- | --- | --- |"]
    rows += [
        f"| {m} | {old.get(m, '-')} | **{new.get(m, '-')}** |"
        for m in sorted(old.keys() | new.keys())
        if old.get(m) != new.get(m)
    ]
    same = sorted(m for m in old if new.get(m) == old[m])
    if same:
        rows.append(f"| {', '.join(same)} | {', '.join(old[m] for m in same)} | unchanged |")
    return rows


def audit_lines(title: str, results: dict, none: str) -> list[str]:
    if not results:
        return [f"- **{title}.** {none}"]
    lines = [f"- **{title}.**"]
    for module, result in sorted(results.items()):
        detail = "; ".join(result["reasons"]) or result.get("note", "")
        lines.append(f"  - {module}: {result['status']}" + (f" ({detail})" if detail else ""))
    return lines


def migration_lines(migrations: dict) -> list[str]:
    """E4's lines: each module's status and reasons, then each admitted migration with its class and sha256."""
    lines = audit_lines("E4 migration diff", migrations, "No `-db` module moved.")
    classes = classifier().CLASSES if any(r.get("admitted") for r in migrations.values()) else {}
    for module, result in sorted(migrations.items()):
        lines += [
            f"  - {module}: migration {m['version']} ({m['name']}) admitted, class {m['statement_class']} "
            f"({classes[m['statement_class']]}), sha256 `{m['checksum']}`"
            for m in result.get("admitted", [])
        ]
    return lines


def platform_lines(platform: dict | None) -> list[str]:
    if not platform:
        return ["- **E1 platform move.** `platform` did not move; the operator Applications are untouched."]
    counts = ", ".join(f"{name} {count}" for name, count in sorted(platform["objects"].items()))
    lines = [
        f"- **E1 platform move {platform['from']} -> {platform['to']}.** The five operator Applications rendered at "
        f"both platforms with `--include-crds` (objects at the target: {counts}); {len(platform['changed'])} image(s) "
        "changed inside the platform-move set:"
    ]
    lines += [f"  - `{c['application']}` `{c['object']}` `{c['field']}`: `{c['image']}`" for c in platform["changed"]]
    return lines


def pr_body(evidence: dict) -> str:
    """The pin PR's body: the template's five sections, final at creation (it is never edited after the push)."""
    pin, target = evidence["pin"], evidence["target"]
    changed = evidence["changed"]
    platform = evidence.get("platform")
    moves = (
        f"moves `scripts/chart_pin.json` to `v{target}` and `platform_version` {platform['to']}, and moves the five "
        f"operator Applications from platform {platform['from']} to **{platform['to']}**"
        if platform
        else f"moves `scripts/chart_pin.json` to `v{target}`"
    )
    what = [
        "## What",
        "",
        f"This PR moves the `yadgar` Application from parent chart {pin} to **{target}**, and {moves}. "
        "**Merging it moves kind-yadgar.** "
        f"`scripts/pin_bump.py` generated the {'eight' if platform else 'three'} files and this body.",
        "",
        f"Verdict of the offline checks: **{'ACCEPT' if evidence['accept'] else 'NEEDS-HUMAN'}**.",
        "",
        *module_table(evidence),
        "",
        f"`v{pin}..v{target}` in `yadgarhq/chart` is {len(evidence['commits'])} commit(s):",
        "",
        "| Commit | Subject |",
        "| --- | --- |",
        *[f"| `{c['sha']}` | {c['subject'].replace('|', '/')} |" for c in evidence["commits"]],
    ]
    why = [
        "## Why",
        "",
        "ADR-0946: each published parent chart version deploys to kind-yadgar automatically, and the ADR-0881 "
        "evidence runs as checks instead of a hand audit.",
    ]
    changelog = ["## Changelog", "", changelog_bullet(evidence)]
    verification = [
        "## Verification",
        "",
        "`scripts/pin_bump.py --check` rendered both pins with this repository's own `valuesObject` on helm "
        f"{', '.join(evidence['helms'])}.",
        "",
        f"- **E1 render diff.** {evidence['objects']} objects at the target; {len(changed)} changed, `image` only:",
        *[
            f"  - `{c['object']}` `{c['field']}`: `{c['digest']}`, the GHCR tag digest of "
            f"`{c['module']}:{c['version']}`"
            for c in changed
        ],
        *audit_lines("E3 boot audit", evidence["boot_audit"], "No module moved."),
        *migration_lines(evidence["migrations"]),
        *platform_lines(platform),
        "- **Not covered here:** E2, the kind-yadgar dry run, is a separate check.",
    ]
    if not evidence["accept"]:
        verification += ["", "**NEEDS-HUMAN.** Each reason below blocks the automatic merge:", ""]
        verification += [f"- {reason}" for reason in evidence["reasons"]]
    rolled = sorted({c["object"] for c in changed})
    crossed = [f"{module} {v}" for module, result in sorted(evidence["migrations"].items()) for v in result.get("forward_only", [])]
    risk = [
        "## Risk",
        "",
        f"What rolls: {', '.join(f'`{o}`' for o in rolled) or 'nothing in the render'}. "
        "A bad image fails its own rollout, and the settled-state gate judges the result after sync.",
        "",
        "**Rollback.**",
        "",
        "1. If `yadgar`'s operation is Running or retrying, first run (NEEDS-MAX) `argocd app terminate-op yadgar`. "
        "Argo CD v3.1.8 has no `retry.refresh`, so a retrying operation keeps applying the bad revision.",
        *(
            [
                "2. Do not revert this PR: it crossed migration(s) " + ", ".join(crossed) + ".",
                "3. A revert is NOT clean. yadgar-store refuses to boot an older binary against a database ahead of it "
                "(DatabaseAhead), so recover by a forward-fix pin (ADR-1099).",
            ]
            if crossed
            else ["2. Revert this PR's commit by PR.", "3. A revert is clean: this pin crosses no migration (E4)."]
        ),
    ]
    return "\n".join(what + [""] + why + [""] + changelog + [""] + verification + [""] + risk) + "\n"


# ── CLI ─────────────────────────────────────────────────────────────────────


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--target", required=True, help="parent chart version X.Y.Z, or `latest`")
    parser.add_argument("--check", action="store_true", help="classify only")
    parser.add_argument("--write", action="store_true", help="rewrite the three mechanical files (eight on a platform move)")
    parser.add_argument("--body", action="store_true", help="print the pull request body")
    parser.add_argument("--evidence", type=Path, help="write the evidence JSON here")
    parser.add_argument("--repo", type=Path, default=REPOSITORY, help=argparse.SUPPRESS)
    arguments = parser.parse_args(argv)
    if not (arguments.check or arguments.write or arguments.body):
        parser.error("say --check, --write and/or --body")

    net = Net()
    evidence = None
    try:
        target = highest_release(net.chart_tags()) if arguments.target == "latest" else arguments.target
        decide(current_pin((arguments.repo / APPLICATION).read_text()), target)
        if arguments.check or arguments.body:
            evidence = check(arguments.repo, target, net, discover_helms())
            if arguments.evidence:
                arguments.evidence.write_text(json.dumps(evidence, indent=2) + "\n")
        if arguments.write:
            written = write_files(arguments.repo, target)
            print(f"wrote {', '.join(written)} for {target}", file=sys.stderr)
    except NoOp as no_op:
        print(f"no-op: {no_op}", file=sys.stderr)
        return EXIT_NO_OP
    except Refused as refused:
        print(f"refused: {refused}", file=sys.stderr)
        return EXIT_ERROR

    if evidence is None:
        return EXIT_ACCEPT
    if arguments.body:
        sys.stdout.write(pr_body(evidence))
    status = "ACCEPT" if evidence["accept"] else "NEEDS-HUMAN"
    print(f"{status}: {evidence['pin']} -> {evidence['target']}, {len(evidence['changed'])} image change(s)", file=sys.stderr)
    for reason in evidence["reasons"]:
        print(f"  - {reason}", file=sys.stderr)
    return EXIT_ACCEPT if evidence["accept"] else EXIT_NEEDS_HUMAN


if __name__ == "__main__":
    sys.exit(main())
