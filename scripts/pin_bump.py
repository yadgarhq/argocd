def operator_inputs(text: str) -> tuple[str, str, list]:
    """`(release name, namespace, value layers)` of an operator Application; refused unless it is the platform shape.

    The layers are `helm.values` (a string) or `helm.valuesObject`, one of them: Argo CD v3.1.8
    `ApplicationSourceHelm.ValuesYAML()` takes `valuesObject` alone when set, so both is refused (as `chart_documents`).
    `valueFiles`, `parameters`, `releaseName` or a `sources` list would be an input this render does not
    reproduce, so they are refused rather than ignored.
    """
    document = yaml.safe_load(text)
    spec = document.get("spec") or {}
    name = (document.get("metadata") or {}).get("name")
    source = spec.get("source")
    if "sources" in spec or not isinstance(source, dict):
        raise Refused(f"operator Application {name}: one `spec.source` is rendered, not `sources`")
    if set(source) - {"repoURL", "chart", "targetRevision", "helm"}:
        raise Refused(f"operator Application {name}: source keys {sorted(source)} are not the platform shape")
    if source.get("repoURL") != PLATFORM_REPO_URL or source.get("chart") != PLATFORM:
        raise Refused(f"operator Application {name}: source is not {PLATFORM_REPO_URL} chart {PLATFORM}")
    helm = source.get("helm") or {}
    if set(helm) - {"values", "valuesObject"}:
        raise Refused(f"operator Application {name}: helm keys {sorted(helm)}; only values and valuesObject are rendered")
    namespace = (spec.get("destination") or {}).get("namespace")
    if not name or not namespace:
        raise Refused("an operator Application without a name or a destination namespace")
    if {"values", "valuesObject"} <= set(helm):
        raise Refused(f"operator Application {name}: helm sets both values and valuesObject; Argo CD renders valuesObject alone, so the two are not layered")
    layers = [helm[key] for key in ("values", "valuesObject") if key in helm]
    return str(name), str(namespace), layers


def operator_template_arguments(name: str, version: str, namespace: str, value_files: list[str]) -> list[str]:
    """`helm template` of the platform chart as Argo CD renders it: release = Application name, CRDs included."""
    arguments = ["template", name, PLATFORM_CHART, "--version", version, "--namespace", namespace, INCLUDE_CRDS]
    arguments += gate("test_no_two_owners").api_version_flags()
    for value_file in value_files:
        arguments += ["--values", value_file]
    return arguments


class HelmInfrastructure(Refused):
    """A `helm` call that failed on the network or the registry (ghcr.io), not on the chart. Retryable, never green.

    A `Refused` for every E1 caller (they fail closed as before). Only E2 step 9 (`pin_dryrun.operator_renders`)
    reads the difference: it reports no result, so auto-pin dispatches the dry run again.
    """


# A chart error `helm` names itself. Checked first: its text may quote a number that looks like a status code.
_TEMPLATE_ERROR = re.compile(r"Error: (?:template:|execution error|YAML parse error|parse error|values don't meet|rendering)", re.I)
# What a dropped connection, a registry outage or a hung call looks like in `helm`'s stderr or in the gates' timeout text.
_TRANSIENT = re.compile(
    r"dial tcp|no such host|temporary failure in name resolution|i/o timeout|handshake timeout|connection (?:reset|refused)"
    r"|unexpected eof|context deadline exceeded|timed out after|service unavailable|bad gateway|gateway timeout"
    r"|too many requests|internal server error",
    re.I,
)


def helm_template(arguments: list[str]) -> str:
    """Run `helm` through the gates' own runner; a template without `--include-crds` is refused (it hides CRDs).

    A failure of the network or the registry raises `HelmInfrastructure` (a `Refused`); a chart error, and any
    failure not recognised as transient, stays a plain `Refused`.
    """
    if arguments[:1] == ["template"] and INCLUDE_CRDS not in arguments:
        raise Refused(f"`helm {' '.join(arguments[:3])}` without {INCLUDE_CRDS}: Argo CD installs the CRDs, so E1 renders them")
    try:
        return gate("test_no_two_owners").helm(*arguments)
    except AssertionError as error:  # the gates' runner reports a failed helm as an AssertionError
        if not _TEMPLATE_ERROR.search(str(error)) and _TRANSIENT.search(str(error)):
            raise HelmInfrastructure(str(error)) from error
        raise Refused(str(error)) from error


def render_operator(text: str, version: str, binary: str) -> list:
    """One operator Application at platform `version`, with its own values, on `binary`."""
    name, namespace, layers = operator_inputs(text)
    with tempfile.TemporaryDirectory() as scratch:
        files = []
        for index, layer in enumerate(layers):
            path = Path(scratch) / f"values-{index}.yaml"
            path.write_text(layer if isinstance(layer, str) else yaml.safe_dump(layer))
            files.append(str(path))
        with helm_on_path(binary):
            rendered = helm_template(operator_template_arguments(name, version, namespace, files))
    return [d for d in yaml.safe_load_all(rendered) if isinstance(d, dict)]


def default_tags(values) -> set[str]:
    """Every non-empty scalar under a key named `tag` in a chart's default values.

    An empty `tag` (most vendored subcharts carry `tag: ""`, meaning "use appVersion") is no tag: kept, it would let
    an untagged image, implicit `:latest`, match it.
    """
    found: set[str] = set()
    if isinstance(values, dict):
        for key, value in values.items():
            if key == "tag" and isinstance(value, (str, int, float)) and not isinstance(value, bool) and str(value):
                found.add(str(value))
            found |= default_tags(value)
    elif isinstance(values, list):
        for value in values:
            found |= default_tags(value)
    return found


def platform_facts(version: str, binary: str) -> dict:
    """`{"lock": {dependency: version}, "charts": {"<name>-<version>": {...}}}` of the platform chart at `version`.

    Read from the published chart itself (`helm pull`): platform's `Chart.lock`, and every vendored chart under
    `charts/` at any depth with its `appVersion`, its default `tag` values, and the top-level dependency it is in.
    """
    with tempfile.TemporaryDirectory() as scratch, helm_on_path(binary):
        helm_template(["pull", PLATFORM_CHART, "--version", version, "--untar", "--untardir", scratch])
        root = Path(scratch) / PLATFORM
        lock = yaml.safe_load((root / "Chart.lock").read_text()) or {}
        charts = {}
        for chart_yaml in sorted((root / "charts").rglob("Chart.yaml")):
            chart = yaml.safe_load(chart_yaml.read_text()) or {}
            values_file = chart_yaml.parent / "values.yaml"
            values = yaml.safe_load(values_file.read_text()) if values_file.exists() else {}
            label = f"{chart.get('name')}-{str(chart.get('version')).replace('+', '_')}"
            charts[label] = {
                "name": str(chart.get("name")),
                "version": str(chart.get("version")),
                "appVersion": str(chart.get("appVersion") or ""),
                "tags": default_tags(values),
                "top": chart_yaml.relative_to(root / "charts").parts[0],
            }
    return {"lock": {str(d["name"]): str(d["version"]) for d in lock.get("dependencies") or []}, "charts": charts}


def tuple_paths(old, new, path: tuple = ()) -> list[tuple]:
    """Every path where `old` and `new` differ, as a tuple of keys and indexes (a label key may hold dots)."""
    if isinstance(old, dict) and isinstance(new, dict):
        return [found for key in sorted(set(old) | set(new)) for found in tuple_paths(old.get(key), new.get(key), (*path, key))]
    if isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        return [found for i, (a, b) in enumerate(zip(old, new, strict=True)) for found in tuple_paths(a, b, (*path, i))]
    return [] if old == new else [path]


def dotted(path: tuple) -> str:
    return "".join(f"[{part}]" if isinstance(part, int) else f".{part}" for part in path).lstrip(".") or "<root>"


def split_reference(reference: str) -> tuple[str, str, str]:
    """`(repository with registry, tag, digest)` of `registry/repo[:tag][@digest]`; a missing part is ''."""
    named, _, digest = reference.partition("@")
    last = named.rsplit("/", 1)[-1]
    if ":" in last:
        repository, _, tag = named.rpartition(":")
        return repository, tag, digest
    return named, "", digest


def render_selector_keys(documents) -> set[str]:
    """Every label key any selector in `documents` reads, on any object but a CRD.

    `matchLabels` keys, `matchExpressions[].key` and the keys a `matchLabelKeys`/`mismatchLabelKeys` list names
    (topologySpreadConstraints, pod affinity terms: the scheduler reads them from the pod's own labels) anywhere
    (a workload, PodDisruptionBudget, NetworkPolicy
    `podSelector`/`namespaceSelector`, ServiceMonitor/PodMonitor `selector`, webhook `objectSelector`, ...), and the
    keys of a plain-map selector under any key ending in `selector` (a Service's `spec.selector`). Over-collecting
    blocks more; under-collecting would let a moved pod label leave a selector's set.
    """
    found: set[str] = set()

    def walk(node, name=None) -> None:
        if isinstance(node, dict):
            if isinstance(node.get("matchLabels"), dict):
                found.update(str(k) for k in node["matchLabels"])
            if isinstance(node.get("matchExpressions"), list):
                found.update(str(e.get("key")) for e in node["matchExpressions"] if isinstance(e, dict))
            for keys in ("matchLabelKeys", "mismatchLabelKeys"):  # topologySpreadConstraints, pod (anti-)affinity
                if isinstance(node.get(keys), list):
                    found.update(k for k in node[keys] if isinstance(k, str))
            plain = not ({"matchLabels", "matchExpressions"} & set(node))
            if plain and str(name).lower().endswith("selector") and all(not isinstance(v, (dict, list)) for v in node.values()):
                found.update(str(k) for k in node)
            for key, value in node.items():
                walk(value, key)
        elif isinstance(node, list):
            for value in node:
                walk(value, name)

    for document in documents:
        if isinstance(document, dict) and document.get("kind") != CRD_KIND:
            walk(document)
    return found


def selector_labels(document: dict) -> set[str]:
    """The label keys a workload's or a Service's selector matches."""
    selector = (document.get("spec") or {}).get("selector") or {}
    if document.get("kind") == "Service":
        return set(selector)
    keys = set(selector.get("matchLabels") or {})
    keys |= {str(e.get("key")) for e in selector.get("matchExpressions") or [] if isinstance(e, dict)}
    return keys


def owning_chart(document: dict, facts: dict) -> dict | None:
    """The vendored chart an object's own `helm.sh/chart` label names, if the platform chart vendors it."""
    label = ((document.get("metadata") or {}).get("labels") or {}).get(CHART_LABEL)
    return facts["charts"].get(str(label)) if label else None


def judge_label(
    key: str, path: tuple, old: dict, new: dict, old_facts: dict, new_facts: dict, *, selected: frozenset | set = frozenset()
) -> list[str]:
    """A changed `helm.sh/chart` or `app.kubernetes.io/version` label; anything else here blocks.

    `selected` is every label key a selector in any Application of the estate reads (`render_selector_keys` over
    them all, ADR-1095). A label whose key is in it blocks wherever it sits, on a pod template or on the object's
    own `metadata.labels`; a pod template label the object's own selector reads blocks too. The match is by key:
    a selector that reads the key on any object counts, which may hold more than it must, never less.
    """
    label = path[-1]
    where = dotted(path)
    own_selector = selector_labels(new) | selector_labels(old) if path[:3] == ("spec", "template", "metadata") else set()
    if label in own_selector | set(selected):
        return [f"{key}: label {where} changed inside a selector"]
    labels_new, labels_old = at_tuple(new, path[:-1]), at_tuple(old, path[:-1])
    value = labels_new.get(label) if isinstance(labels_new, dict) else None
    before = labels_old.get(label) if isinstance(labels_old, dict) else None
    if label == CHART_LABEL:
        now, then = new_facts["charts"].get(str(value)), old_facts["charts"].get(str(before))
        if not now or not then or now["name"] != then["name"]:
            return [f"{key}: label {where} {before} -> {value} is not a vendored subchart's version move"]
        return []
    chart = owning_chart(new, new_facts)
    if not chart or str(value) != chart["appVersion"]:
        return [f"{key}: label {where} -> {value} is not the appVersion of the subchart its {CHART_LABEL} names"]
    return []


def at_tuple(document, path: tuple):
    node = document
    for part in path:
        try:
            node = node[part]
        except (KeyError, IndexError, TypeError):
            return None
    return node


def judge_operator_image(key, path, old_image, new_image, document, old_facts, new_facts, registry_digest) -> tuple[dict | None, list[str]]:
    """One changed operator image against the tag-only or the digest-pinned rule."""
    where = dotted(path)
    old_repository, _, old_digest = split_reference(str(old_image))
    repository, tag, digest = split_reference(str(new_image))
    if repository != old_repository:
        return None, [f"{key}: {where} repository changed {old_repository} -> {repository}"]
    entry = {"object": key, "field": where, "image": str(new_image)}
    if digest:
        if not tag:
            return None, [f"{key}: {where} is digest-pinned with no tag, so no registry tag can vouch for {digest}"]
        try:
            expected = registry_digest(repository, tag)
        except Exception as error:  # noqa: BLE001  (an unreadable registry is a red, never a green)
            return None, [f"{key}: the tag digest of {repository}:{tag} could not be read ({error})"]
        if digest != expected:
            return None, [f"{key}: {where} digest {digest} is not the registry's digest of {repository}:{tag} ({expected})"]
        return entry, []
    if old_digest:
        return None, [f"{key}: {where} dropped its digest ({old_image} -> {new_image})"]
    if not tag:
        return None, [f"{key}: {where} {new_image} has no tag and no digest (an implicit :latest)"]
    chart = owning_chart(document, new_facts)
    if not chart:
        return None, [f"{key}: {where} is tag-only and its {CHART_LABEL} label names no vendored subchart"]
    problems = []
    if tag != chart["appVersion"] and tag not in chart["tags"]:
        problems.append(f"{key}: {where} tag {tag} is neither {chart['name']}'s appVersion {chart['appVersion']} nor a default tag")
    top = chart["top"]
    if old_facts["lock"].get(top) == new_facts["lock"].get(top):
        problems.append(f"{key}: {where} moved but subchart {top} did not move in platform's Chart.lock ({new_facts['lock'].get(top)})")
    return (None if problems else entry), problems


def schema_problems(key: str, version: str, old, new, path: str) -> list[str]:
    """A CRD version's openAPIV3Schema: only a new optional property with no default may appear."""
    if not (isinstance(old, dict) and isinstance(new, dict)):
        return [] if old == new else [f"{key}: {version} schema {path} changed"]
    problems = []
    for name in sorted((set(old) | set(new)) - {"properties"}):
        if name in ("items", "additionalProperties") and isinstance(old.get(name), dict) and isinstance(new.get(name), dict):
            problems += schema_problems(key, version, old[name], new[name], f"{path}.{name}")
        elif old.get(name) != new.get(name):
            problems.append(f"{key}: {version} schema {path}.{name} changed ({name}: {old.get(name)!r} -> {new.get(name)!r})")
    before, after = old.get("properties") or {}, new.get("properties") or {}
    for name in sorted(before.keys() - after.keys()):
        problems.append(f"{key}: {version} schema property {path}.properties.{name} removed")
    for name in sorted(after.keys() - before.keys()):
        if name in (new.get("required") or []):
            problems.append(f"{key}: {version} schema property {path}.properties.{name} added as required")
        elif default_anywhere(after[name]):
            problems.append(f"{key}: {version} schema property {path}.properties.{name} added with a default")
    for name in sorted(before.keys() & after.keys()):
        problems += schema_problems(key, version, before[name], after[name], f"{path}.properties.{name}")
    return problems


def default_anywhere(schema) -> bool:
    if isinstance(schema, dict):
        return "default" in schema or any(default_anywhere(v) for v in schema.values())
    if isinstance(schema, list):
        return any(default_anywhere(v) for v in schema)
    return False


def crd_problems(
    key: str, old: dict, new: dict, old_facts: dict, new_facts: dict, *, selected: frozenset | set = frozenset()
) -> list[str]:
    """The CRD allowlist: (a) a new optional property with no default, (b) a new served version with the storage
    version and conversion unchanged, plus the derived chart labels outside any selector. Everything else blocks."""
    problems = []
    rest_old, rest_new = copy.deepcopy(old), copy.deepcopy(new)
    versions_old = (rest_old.get("spec") or {}).pop("versions", None) or []
    versions_new = (rest_new.get("spec") or {}).pop("versions", None) or []
    for path in tuple_paths(rest_old, rest_new):
        if path[:2] == ("metadata", "labels") and len(path) == 3 and path[2] in DERIVED_LABELS:
            problems += judge_label(key, path, old, new, old_facts, new_facts, selected=selected)
        else:
            problems.append(f"{key}: field {dotted(path)} changed; a CRD may only add an optional property or a served version")
    by_old = {str(v.get("name")): v for v in versions_old}
    by_new = {str(v.get("name")): v for v in versions_new}
    storage_old = sorted(n for n, v in by_old.items() if v.get("storage"))
    storage_new = sorted(n for n, v in by_new.items() if v.get("storage"))
    if storage_old != storage_new:
        problems.append(f"{key}: storage version changed {storage_old} -> {storage_new}")
    problems += [f"{key}: version {name} removed" for name in sorted(by_old.keys() - by_new.keys())]
    for name in sorted(by_old.keys() & by_new.keys()):
        a, b = dict(by_old[name]), dict(by_new[name])
        schema_a = (a.pop("schema", None) or {}).get("openAPIV3Schema")
        schema_b = (b.pop("schema", None) or {}).get("openAPIV3Schema")
        problems += [f"{key}: version {name} field {dotted(p)} changed" for p in tuple_paths(a, b)]
        problems += schema_problems(key, name, schema_a, schema_b, "openAPIV3Schema")
    return problems


def classify_platform(renders: dict, old_facts: dict, new_facts: dict, registry_digest, *, others: list = ()) -> PlatformVerdict:
    """E1 of a platform move. `renders` is `{helm version: {Application: (base documents, head documents)}}`.

    `others` is the render of every other Application of the estate: `yadgar` at both pins, root and what it
    selects (`estate_selectors`). Their selectors and those of every operator Application at both pins are
    collected ONCE, before any object is judged (ADR-1095): a ServiceMonitor in one Application may select
    another's Service.
    """
    digests = gate("test_yadgar_application").digests
    verdict = PlatformVerdict()
    helms = sorted(renders)
    if len(helms) < 2:
        verdict.reasons.append(f"platform: only one helm version rendered ({', '.join(helms) or 'none'}); acceptance needs two that agree")
    if not helms or not renders[helms[0]]:
        verdict.reasons.append("platform moved but no operator Application was rendered")
        return verdict
    first = helms[0]
    selected = render_selector_keys(
        [*others, *(d for base, head in renders[first].values() for d in (*base, *head))]
    )
    for application in sorted(renders[first]):
        for other in helms[1:]:
            for side, index in (("base", 0), ("head", 1)):
                a = digests(renders[first][application][index])
                b = digests((renders[other].get(application) or ([], []))[index])
                if a != b:
                    differing = sorted(k for k in a.keys() | b.keys() if a.get(k) != b.get(k))
                    verdict.reasons.append(f"{application}: helm {first} and helm {other} disagree at the {side} platform: {', '.join(differing)}")
        base, head = (objects_of(documents) for documents in renders[first][application])
        verdict.objects[application] = len(head)
        for side, objects in (("base", base), ("head", head)):
            if not objects:
                verdict.reasons.append(f"{application}: renders no object at the {side} platform; an empty render proves nothing")
        verdict.reasons += [f"{application}: object removed: {k}" for k in sorted(base.keys() - head.keys())]
        verdict.reasons += [f"{application}: object added: {k}" for k in sorted(head.keys() - base.keys())]
        for key in sorted(base.keys() & head.keys()):
            old, new = base[key], head[key]
            if old == new:
                continue
            if new.get("kind") == CRD_KIND or old.get("kind") == CRD_KIND:
                verdict.reasons += [
                    f"{application}: {p}" for p in crd_problems(key, old, new, old_facts, new_facts, selected=selected)
                ]
                continue
            for path in tuple_paths(old, new):
                kind = new.get("kind")
                image = (
                    kind in OPERATOR_WORKLOAD_KINDS
                    and len(path) == 6
                    and path[:4] == ("spec", "template", "spec", "containers")
                    and path[5] == "image"
                )
                label = path[-1] in DERIVED_LABELS and path[:-1] in (("metadata", "labels"), ("spec", "template", "metadata", "labels"))
                if image:
                    entry, problems = judge_operator_image(
                        key, path, at_tuple(old, path), at_tuple(new, path), new, old_facts, new_facts, registry_digest
                    )
                    verdict.reasons += [f"{application}: {p}" for p in problems]
                    if entry:
                        verdict.changed.append({"application": application, **entry})
                elif label:
                    verdict.reasons += [
                        f"{application}: {p}" for p in judge_label(key, path, old, new, old_facts, new_facts, selected=selected)
                    ]
                else:
                    verdict.reasons.append(f"{application}: {key}: field {dotted(path)} changed; outside the platform-move set")
    return verdict


def platform_evidence(repo: Path, old: str, new: str, helms: dict[str, str], net: Net, others: list) -> dict:
    """The platform move's E1: the five operator Applications of `repo` rendered at `old` and `new` on every helm.

    `others` is every `yadgar` render `check` made. Its selectors, the operators' at both pins and those of every
    other Application of the estate (`estate_selectors`, ADR-1095) are one set. An Application whose source cannot
    be read for selectors is a reason, never a skip. The live operators and CRDs are compared by `pin_dryrun.py`
    (E2-interim, car C10 part 2), not here.
    """
    texts = {}
    for path in OPERATOR_APPLICATIONS:
        name = Path(path).stem
        texts[name] = (repo / path).read_text()
    renders = {
        label: {name: (render_operator(text, old, binary), render_operator(text, new, binary)) for name, text in texts.items()}
        for label, binary in sorted(helms.items())
    }
    estate, documents, unread = estate_selectors(repo, helms, in_hand=(APPLICATION, *OPERATOR_APPLICATIONS))
    binary = helms[sorted(helms)[0]]
    verdict = classify_platform(
        renders, platform_facts(old, binary), platform_facts(new, binary), net.registry_digest, others=[*others, *documents]
    )
    keys = {name: sorted(found) for name, found in estate.items()}
    keys[Path(APPLICATION).stem] = sorted(render_selector_keys(others))
    for name in texts:
        keys[name] = sorted(render_selector_keys([d for r in renders.values() for d in (*r[name][0], *r[name][1])]))
    return {
        "from": old,
        "to": new,
        "objects": verdict.objects,
        "changed": verdict.changed,
        "applications": sorted(keys),
        "selector_keys": dict(sorted(keys.items())),
        "reasons": unread + verdict.reasons,
    }


# ── ADR-1095: the selector keys of EVERY Application of the estate ──────────
#
# A derived label counts as inside a selector when any label selector in any
# Argo CD Application of the estate reads its key. The estate is root
# (`projects/root.yaml`) and every Application root's directory source selects,
# found by reading that source, never from a list: a new Application file is in
# scope with no code change. `yadgar` and the five operator Applications are
# rendered by `check` and `platform_evidence` at both pins already; every other
# one is read here once, at this tree, on every helm (the keys are unioned).
#
# Only what this reader reproduces exactly is read; anything else is a reason
# (NEEDS-HUMAN), never a skip. A directory source of THIS repository at
# `main`/`HEAD` (plain manifests: `.yaml`, `.yml`, `.json`; `recurse` and a
# plain `include` glob only, matched as Argo CD does with `*` crossing `/`; no
# kustomization, `Chart.yaml` or jsonnet in it; no `kind: List`);
# a `ref:` source of this repository (renders nothing); a helm chart at one
# exact version, OCI when its `repoURL` has no scheme, with `values` or
# `valuesObject` (not both: Argo CD drops `values` then), `releaseName` and
# `valueFiles` that name a `ref:` source. An in-hand Application is skipped
# only when root lists it exactly as its file reads. An
# ApplicationSet, or an Application inside another Application's render, would
# bring in Applications this reader cannot see, so both are reasons too.

ROOT_APPLICATION = "projects/root.yaml"
THIS_REPOSITORY = "https://github.com/yadgarhq/argocd"
TREE_REVISIONS = frozenset({"main", "HEAD"})
MANIFEST_SUFFIXES = (".yaml", ".yml", ".json")
NOT_PLAIN = frozenset({"kustomization.yaml", "kustomization.yml", "Kustomization", "Chart.yaml"})
CHART_VERSION = re.compile(r"^v?\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.+-]+)?$")


def this_repository(url) -> bool:
    return str(url).rstrip("/").removesuffix(".git") == THIS_REPOSITORY


def sources_of(application: dict) -> list:
    """`spec.source`, then each `spec.sources` entry; refused when there is neither."""
    spec = application.get("spec") or {}
    found = [spec["source"]] if isinstance(spec.get("source"), dict) else []
    if isinstance(spec.get("sources"), list):
        found += [s for s in spec["sources"] if isinstance(s, dict)]
    if not found:
        raise Refused("no `spec.source` or `spec.sources`")
    return found


def glob_matches(pattern: str, relative: str) -> bool:
    """Argo CD v3.1.8's `directory.include` match: gobwas `glob.Match` with no separators, so `*` crosses `/`
    (`reposerver/repository/repository.go`). `applications/*.yaml` matches `applications/sub/x.yaml`."""
    return fnmatch.fnmatchcase(relative, pattern)


def directory_documents(repo: Path, source: dict) -> list:
    """Every document a plain-manifest directory source of this repository renders."""
    if set(source) - {"repoURL", "targetRevision", "path", "directory"}:
        raise Refused(f"source keys {sorted(source)}; only a plain directory is read")
    if not this_repository(source.get("repoURL")):
        raise Refused(f"path `{source.get('path')}` is on {source.get('repoURL')}, not this repository")
    if source.get("targetRevision") not in TREE_REVISIONS:
        raise Refused(f"path `{source.get('path')}` at revision {source.get('targetRevision')!r}; this tree is main")
    directory = source.get("directory") or {}
    include = str(directory.get("include") or "")
    if set(directory) - {"recurse", "include"} or any(c in include for c in "{}[]\\"):
        raise Refused(f"directory options {directory}; only `recurse` and a plain `include` glob are read")
    top = (repo / str(source["path"])).resolve()
    if not top.is_dir() or not top.is_relative_to(repo.resolve()):
        raise Refused(f"path `{source['path']}` is no directory of this tree")
    # Argo CD picks kustomize or helm from the files at the path itself; a directory renders jsonnet it includes.
    if built := sorted(NOT_PLAIN & {p.name for p in top.iterdir()}):
        raise Refused(f"`{source['path']}` holds {', '.join(built)}: Argo CD would build it as kustomize or helm")
    files = []
    for folder, subfolders, names in os.walk(top):
        subfolders[:] = sorted(s for s in subfolders if s != ".git") if directory.get("recurse") else []
        for name in sorted(names):
            relative = (Path(folder) / name).relative_to(top).as_posix()
            if include and not glob_matches(include, relative):
                continue
            if name.endswith((".jsonnet", ".libsonnet")):
                raise Refused(f"`{source['path']}/{relative}`: Argo CD would evaluate this jsonnet")
            if name.endswith(MANIFEST_SUFFIXES):
                files.append(Path(folder) / name)
    return [d for path in files for d in yaml.safe_load_all(path.read_text()) if isinstance(d, dict)]


def chart_source_arguments(name: str, namespace: str, source: dict, value_files: list[str]) -> list[str]:
    """`helm template` of a chart source as Argo CD renders it: release = `releaseName` or the Application's name."""
    release = str((source.get("helm") or {}).get("releaseName") or name)
    url = str(source["repoURL"])
    if "://" in url:
        arguments = ["template", release, str(source["chart"]), "--repo", url]
    else:
        arguments = ["template", release, f"oci://{url.rstrip('/')}/{source['chart']}"]
    arguments += ["--version", str(source["targetRevision"]), "--namespace", namespace, INCLUDE_CRDS]
    arguments += gate("test_no_two_owners").api_version_flags()
    for value_file in value_files:
        arguments += ["--values", value_file]
    return arguments


def render_chart_source(name: str, namespace: str, source: dict, value_files: list[str], binary: str) -> list:
    """One chart source rendered on `binary`."""
    with helm_on_path(binary):
        rendered = helm_template(chart_source_arguments(name, namespace, source, value_files))
    return [d for d in yaml.safe_load_all(rendered) if isinstance(d, dict)]


def chart_documents(repo: Path, name: str, namespace: str, source: dict, refs: dict, binary: str) -> list:
    """A helm chart source, its value layers in Argo CD's order: `valueFiles`, then `values` or `valuesObject`."""
    if set(source) - {"repoURL", "chart", "targetRevision", "helm"}:
        raise Refused(f"chart source keys {sorted(source)}")
    if not CHART_VERSION.match(str(source.get("targetRevision", ""))):
        raise Refused(f"chart {source.get('chart')} at {source.get('targetRevision')!r}, not one exact version")
    helm = source.get("helm") or {}
    if set(helm) - {"values", "valuesObject", "valueFiles", "releaseName"}:
        raise Refused(f"helm keys {sorted(helm)}; only values, valuesObject, valueFiles and releaseName are rendered")
    if {"values", "valuesObject"} <= set(helm):
        # Argo CD v3.1.8 `ApplicationSourceHelm.ValuesYAML()` takes `valuesObject` alone when set and drops `values`.
        raise Refused("helm sets both values and valuesObject; Argo CD renders valuesObject alone, so the two are not layered")
    layers = []
    for value_file in helm.get("valueFiles") or []:
        ref, _, rest = str(value_file).partition("/")
        if not ref.startswith("$") or ref[1:] not in refs or not rest:
            raise Refused(f"valueFile {value_file!r} names no `ref:` source of this repository")
        path = (repo / rest).resolve()
        if not path.is_file() or not path.is_relative_to(repo.resolve()):
            raise Refused(f"valueFile {value_file!r}: `{rest}` is no file of this tree")
        layers.append(path.read_text())
    layers += [helm[key] if isinstance(helm[key], str) else yaml.safe_dump(helm[key]) for key in ("values", "valuesObject") if key in helm]
    with tempfile.TemporaryDirectory() as scratch:
        files = []
        for index, layer in enumerate(layers):
            files.append(str(Path(scratch) / f"values-{index}.yaml"))
            Path(files[-1]).write_text(layer)
        return render_chart_source(name, namespace, source, files, binary)


def application_documents(repo: Path, application: dict, binary: str) -> list:
    """Every document one Application renders from this tree on `binary`; Refused for anything not reproduced."""
    name = str((application.get("metadata") or {}).get("name") or "")
    namespace = ((application.get("spec") or {}).get("destination") or {}).get("namespace")
    sources = sources_of(application)
    refs = {}
    for source in sources:
        if "ref" in source:
            if set(source) - {"repoURL", "targetRevision", "ref"} or not this_repository(source.get("repoURL")):
                raise Refused(f"`ref: {source['ref']}` source {sorted(source)} on {source.get('repoURL')}; only this repository is read")
            if source.get("targetRevision") not in TREE_REVISIONS:
                raise Refused(f"`ref: {source['ref']}` at revision {source.get('targetRevision')!r}; this tree is main")
            refs[str(source["ref"])] = source
    documents = []
    for source in sources:
        if "ref" in source:
            continue
        if "chart" in source:
            if not namespace:
                raise Refused("a chart source with no destination namespace")
            documents += chart_documents(repo, name, str(namespace), source, refs, binary)
        elif "path" in source:
            documents += directory_documents(repo, source)
        else:
            raise Refused(f"source keys {sorted(source)}: neither a chart, a path nor a ref")
    return documents


def list_documents(documents: list) -> list[str]:
    """The kinds of every List document (a kind ending in `List` with `items`): Argo CD applies each item."""
    return sorted({str(d.get("kind")) for d in documents if str(d.get("kind", "")).endswith("List") and "items" in d})


def estate_selectors(repo: Path, helms: dict[str, str], *, in_hand: tuple = ()) -> tuple[dict[str, set[str]], list, list[str]]:
    """`({Application: selector keys}, documents, reasons)` over root and every Application root selects.

    `in_hand` names the Application files whose renders the caller holds: root lists them, they are not rendered
    again here. A chart source is rendered on every helm in `helms`, a directory read once. Each reason reads
    `selectors: Application <name>: cannot be read for selectors (...)`.
    """
    keys: dict[str, set[str]] = {}
    documents: list = []
    reasons: list[str] = []

    def unread(name: str, why) -> None:
        reasons.append(f"selectors: Application {name}: cannot be read for selectors ({why}); ADR-1095 leaves no Application out")

    if not (repo / ROOT_APPLICATION).is_file():
        unread("root", f"`{ROOT_APPLICATION}` is absent")
        return keys, documents, reasons
    try:
        listed = application_documents(repo, yaml.safe_load((repo / ROOT_APPLICATION).read_text()) or {}, "")
    except Refused as refused:
        unread("root", refused)
        return keys, documents, reasons
    if lists := list_documents(listed):
        unread("root", f"it lists {', '.join(lists)}; Argo CD expands a List, and an Application inside one is not followed")
        return keys, documents, reasons
    keys["root"] = render_selector_keys(listed)
    documents += listed
    for document in listed:
        if document.get("kind") == "ApplicationSet":
            unread("root", f"ApplicationSet {(document.get('metadata') or {}).get('name')} generates Applications this reader cannot see")
    # Skipped only when equal to the parsed in-hand file: another file reusing its name is read like any other.
    hand = [yaml.safe_load((repo / path).read_text()) for path in in_hand if (repo / path).is_file()]
    for application in (d for d in listed if d.get("kind") == "Application"):
        name = str((application.get("metadata") or {}).get("name") or "<unnamed>")
        if application in hand:
            continue
        found: list = []
        try:
            charted = any("chart" in source for source in sources_of(application))
            for binary in [helms[label] for label in sorted(helms)] if charted else [""]:
                rendered = application_documents(repo, application, binary)
                nested = sorted({str(d["kind"]) for d in rendered if d.get("kind") in ("Application", "ApplicationSet")})
                if nested:
                    raise Refused(f"it renders {', '.join(nested)}; a nested Application is not followed")
                if lists := list_documents(rendered):
                    raise Refused(f"it renders {', '.join(lists)}; Argo CD expands a List, and its items are not read")
                found += rendered
        except Refused as refused:
            unread(name, refused)
            continue
        keys[name] = render_selector_keys(found)
        documents += found
    return keys, documents, reasons


# ── reading Rust source ─────────────────────────────────────────────────────

TEST_MODULE = re.compile(r"#\[cfg\(test\)\]\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{")
CHAR_LITERAL = re.compile(r"'(?:\\u\{[0-9a-fA-F]{1,6}\}|\\.|[^\\'\n])'")
RAW_STRING = re.compile(r'b?r(#*)"')


def code_mask(text: str) -> str:
    """`text` with the inside of every comment, string and char literal blanked to spaces, same length.

    What a brace counter or a call-site search reads, so a `{` in `"{"`, `'{'`,
    `r#"{"#`, `// {` or `/* { */` is never code. Newlines are kept. A lifetime
    (`'a`) is not a char literal and stays code.
    """
    out = list(text)
    length = len(text)

    def blank(start: int, stop: int) -> None:
        for k in range(start, stop):
            if out[k] != "\n":
                out[k] = " "

    i = 0
    while i < length:
        if text.startswith("//", i):
            stop = text.find("\n", i)
            stop = length if stop < 0 else stop
            blank(i, stop)
            i = stop
            continue
        if text.startswith("/*", i):
            depth, j = 0, i
            while j < length:
                if text.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif text.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                    if depth == 0:
                        break
                else:
                    j += 1
            blank(i, j)
            i = j
            continue
        boundary = i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")
        raw = RAW_STRING.match(text, i) if boundary and text[i] in "rb" else None
        if raw:
            close = '"' + raw.group(1)
            stop = text.find(close, raw.end())
            stop = length if stop < 0 else stop
            blank(raw.end(), stop)
            i = min(length, stop + len(close))
            continue
        if text[i] == '"':
            j = i + 1
            while j < length and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            blank(i + 1, min(j, length))
            i = j + 1
            continue
        if text[i] == "'" and (char := CHAR_LITERAL.match(text, i)):
            blank(i + 1, char.end() - 1)
            i = char.end()
            continue
        i += 1
    return "".join(out)


def matching_brace(mask: str, opening: int) -> int:
    """Index just past the `}` closing the `{` at `opening`, counted on a `code_mask`."""
    depth = 0
    for index in range(opening, len(mask)):
        if mask[index] == "{":
            depth += 1
        elif mask[index] == "}":
            depth -= 1
            if depth == 0:
                return index + 1
    return len(mask)


def without_test_modules(text: str) -> str:
    while match := TEST_MODULE.search(mask := code_mask(text)):
        text = text[: match.start()] + text[matching_brace(mask, match.end() - 1) :]
    return text


def is_test_path(path: str) -> bool:
    parts = Path(path).parts
    name = parts[-1]
    return "tests" in parts[:-1] or name == "tests.rs" or name.endswith(("_tests.rs", "_test.rs"))


def production_sources(source: dict[str, str]) -> dict[str, str]:
    """Non-test `src/**/*.rs`, with `#[cfg(test)] mod … { }` blocks removed."""
    return {
        path: without_test_modules(text)
        for path, text in sorted(source.items())
        if path.startswith("src/") and path.endswith(".rs") and not is_test_path(path)
    }


# ── E3: the boot audit ──────────────────────────────────────────────────────

# AN UPPER-SNAKE LITERAL COUNTS ONLY AS AN ENV NAME AT AN ENV-READ CALL SITE
# (coordinator ruling, ledger 1632): error codes such as `NOT_FOUND` and
# `PROJECT_ARCHIVED` are not env names. The call sites are every pattern the
# seven module repos and seeder use, grepped 2026-10-18 at their latest tags:
#
#   required  `env_required*(…)` (`env_required`, `_allow_empty`, `_chart`,
#             `_named`), `env_parsed(…)` (task-db) and `parse_bucket_env(…)`
#             (gateway): each refuses to boot on an absent key;
#   read      `std::env::var(…)`, `env::var_os(…)`, and a call to a lookup
#             closure parameter typed `impl Fn(&str) -> Option<String>` —
#             gateway's `from_lookup(lookup: …)` reads `lookup(KEY)`, the -db
#             modules' `boot(env: …)` read `env(KEY)`;
#   wrapped   a local closure whose body calls one of the above — seeder's
#             `let required = |var| match lookup(var) …` — read only inside
#             the block that binds it (a `let` cannot be named outside it, so
#             gateway's tls.rs `let get = |suffix| …` never makes axum's
#             `get(whoami)` in another fn a read; a closure whose name
#             appears in that block other than as a call — passed, returned,
#             stored — escapes, and stays a reader crate-wide), and a `fn` or
#             `macro_rules!` whose body calls one keyed on its own parameter
#             (`fn get(k) { std::env::var(k) }`, `req!($k)`) are readers too,
#             required ones when the name says `required` or the body calls a
#             required reader. Followed to a fixpoint.
#
# The key is the first or second argument: a string literal, or a `const` of
# type `&str` defined anywhere in the crate, by bare or path-qualified name
# (`config::HOST`). When the first argument is itself upper-snake (`f(K9, D)`),
# the site is unresolved rather than keyed on the second.
#
# FAIL-CLOSED ON WHAT IT CANNOT READ, by coarse tripwires counted at both tags
# (a false NEEDS-HUMAN is cheap; a false ACCEPT deploys something unvetted):
#
#   - a call site whose key is none of those (`lookup(&format!(…))`, a
#     variable, a const from another crate), counted per (enclosing fn,
#     normalised text, hash of the enclosing fn's normalised body): any
#     growth is NEEDS-HUMAN. The file is not in the key, so a fn moved
#     verbatim between files is no growth; the body hash makes a different
#     fn of the same name, or the same fn with a changed binding, growth;
#   - a call into an env entry point whose reads happen elsewhere —
#     `*from_env*`, `*from_lookup*` (lifecycle's `ServerTls::from_env` reads
#     `{prefix}_TLS_*`, dial's `request_timeout_from_lookup` its own key), or
#     any call handed a reader as an argument: any growth per callee;
#   - the token tripwire (`TRIPWIRE` below): `std::env`, `use std::env`,
#     `env::vars`, `dotenv`, `envy`, `Fn(&str)`, an attribute `env =` (clap):
#     any growth per token;
#   - Cargo.toml and Cargo.lock (`crate_findings`): a moved, unpinnable or
#     overridden `yadgar-*` crate, and any `yadgar-*` change in the lock.
CONST_STR = re.compile(r'\bconst\s+([A-Z][A-Z0-9_]*)\s*:\s*&(?:\'static\s+)?str\s*=\s*"([^"\\]*)"\s*;')
LOOKUP_PARAMETER = re.compile(
    r"\b([a-z_][a-z0-9_]*)\s*:\s*&?\s*(?:impl|dyn)\s+Fn\s*\(\s*&str\s*\)\s*->\s*Option\s*<\s*String\s*>"
)
LOCAL_CLOSURE = re.compile(r"\blet\s+(?:mut\s+)?([a-z_][a-z0-9_]*)\s*=\s*(?:move\s+)?\|([^|]*)\|")
FN_DEFINITION = re.compile(r"\bfn\s+([a-z_][a-z0-9_]*)\s*(?:<[^>{(]*>)?\s*\(")
MACRO_DEFINITION = re.compile(r"\bmacro_rules!\s*([a-z_][a-z0-9_]*)\s*\{")
REQUIRED_READERS = ("env_required\\w*", "env_parsed", "parse_bucket_env")
KEY_ARGUMENT = re.compile(
    r'\s*\(\s*([^()";,]*,\s*)?(?:"([A-Z][A-Z0-9_]*)"|(?:[A-Za-z_]\w*::)*([A-Z][A-Z0-9_]*)\b)(?=\s*[,)])'
)
UPPER_TOKEN = re.compile(r"\b[A-Z][A-Z0-9_]*\b")
CALL = re.compile(r"(?<![\w.])((?:[A-Za-z_]\w*::)*[A-Za-z_]\w*)\s*\(")
NOT_CALLS = frozenset({"if", "while", "match", "for", "return", "fn", "Some", "Ok", "Err", "loop", "in"})
# A call into a shared crate's env read: the keys it reads are not in this source.
ENTRY_POINT = re.compile(r"(?<![\w.])((?:[A-Za-z_]\w*::)*\w*from_(?:env|lookup)\w*)\s*\(")
# THE TOKEN TRIPWIRE: every way to reach the environment that the call-site
# reading above does not model. Counted per tag on the code mask; any count that
# grows is NEEDS-HUMAN. Coarse on purpose: a false NEEDS-HUMAN is cheap, a false
# ACCEPT deploys something unvetted.
TRIPWIRE = {
    "std::env": re.compile(r"\bstd\s*::\s*env\b"),
    "use std::env": re.compile(r"\buse\s+std\s*::\s*env\b"),
    "env::vars": re.compile(r"\benv\s*::\s*vars(?:_os)?\b"),
    "dotenv": re.compile(r"dotenv"),
    "envy": re.compile(r"\benvy\b"),
    "Fn(&str)": re.compile(r"\bFn\s*\(\s*&\s*str\s*\)"),
    "attribute env =": re.compile(r"#\s*!?\s*\[[^\]]*\benv\s*="),
}


def matching_paren(mask: str, opening: int) -> int:
    """Index just past the `)` closing the `(` at `opening`, counted on a `code_mask`."""
    depth = 0
    for index in range(opening, len(mask)):
        depth += {"(": 1, ")": -1}.get(mask[index], 0)
        if depth == 0:
            return index + 1
    return len(mask)


def arguments(mask: str, opening: int) -> list[str]:
    """The top-level arguments of the call whose `(` is at `opening`, as masked text."""
    inner = mask[opening + 1 : matching_paren(mask, opening) - 1]
    parts, depth, current = [], 0, ""
    for char in inner:
        depth += {"(": 1, "[": 1, "{": 1, "<": 1, ")": -1, "]": -1, "}": -1, ">": -1}.get(char, 0)
        if char == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += char
    return [part.strip() for part in parts + [current] if part.strip()]


def bare(argument: str) -> str:
    return re.sub(r"^&\s*(?:mut\s+)?", "", argument).strip()


def reader_call(required: set[str], read: set[str]) -> re.Pattern:
    names = lambda group: "|".join(sorted(group))  # noqa: E731
    pattern = rf"(?P<required>(?<![\w.])(?:{names(required)}))"
    pattern += r"|(?P<read>\benv::var(?:_os)?"
    pattern += rf"|(?<![\w.])(?:{names(read)}))" if read else ")"
    return re.compile(rf"(?:{pattern})(?=\s*\()")


def enclosing_block_end(mask: str, position: int) -> int:
    """Index just past the `}` closing the innermost `{` that encloses `position`, counted on a `code_mask`."""
    depth = 0
    for index in range(position - 1, -1, -1):
        if mask[index] == "}":
            depth += 1
        elif mask[index] == "{":
            if depth == 0:
                return matching_brace(mask, index)
            depth -= 1
    return len(mask)


def wrappers(mask: str) -> list[tuple[str, str, set[str], int, int, tuple[int, int] | None]]:
    """`(kind, name, parameters, body start, body stop, scope)` of every local closure, fn and macro_rules! in
    `mask`. `scope` is a closure's `(binding, end of its enclosing block)`, the only span that can name it;
    None for a fn or macro, which the crate can name anywhere, and for a closure whose value escapes that span."""
    found = []
    for closure in LOCAL_CLOSURE.finditer(mask):
        parameters = set(re.findall(r"([a-z_]\w*)\s*(?::|$|,)", closure.group(2)))
        brace, semicolon = mask.find("{", closure.end()), mask.find(";", closure.end())
        stop = matching_brace(mask, brace) if 0 <= brace < semicolon or semicolon < 0 <= brace else semicolon
        scope: tuple[int, int] | None = (closure.start(), enclosing_block_end(mask, closure.start()))
        uses = re.finditer(rf"(?<![\w.]){re.escape(closure.group(1))}\b(?!\s*\()", mask[closure.end() : scope[1]])
        if next(uses, None) is not None:
            scope = None  # the closure value escapes (passed, returned, stored, aliased): crate-wide, as before
        found.append(("closure", re.escape(closure.group(1)), parameters, closure.end(), stop if stop > 0 else len(mask), scope))
    for function in FN_DEFINITION.finditer(mask):
        close = matching_paren(mask, function.end() - 1)
        parameters = set(re.findall(r"(?:^|[,(])\s*(?:mut\s+)?([a-z_]\w*)\s*:", mask[function.end() - 1 : close]))
        brace = mask.find("{", close)
        if brace >= 0 and ";" not in mask[close:brace]:
            found.append(("fn", re.escape(function.group(1)), parameters, brace, matching_brace(mask, brace), None))
    for macro in MACRO_DEFINITION.finditer(mask):
        stop = matching_brace(mask, macro.end() - 1)
        parameters = {f"${name}" for name in re.findall(r"\$([a-z_]\w*)\s*:", mask[macro.end() : stop])}
        found.append(("macro", re.escape(macro.group(1)) + "!", parameters, macro.end(), stop, None))
    return found


Scopes = dict[str, list[tuple[str, int, int]]]


def visible(scopes: Scopes, matched: str, path: str, position: int) -> bool:
    """Whether the reader call `matched` at `position` in `path` names a reader: always for a crate-wide one,
    and for a closure-only name only inside a block that binds it."""
    spans = scopes.get(re.escape(matched))
    return spans is None or any(p == path and start <= position < stop for p, start, stop in spans)


def readers_of(files: dict[str, str], masks: dict[str, str]) -> tuple[set[str], set[str], Scopes]:
    """`(required reader names, plain reader names, scopes)`: the fixed ones, lookup parameters, and every
    closure, fn or macro_rules! whose body calls a reader keyed on one of its own parameters (or, for a
    closure, at all). `scopes` maps a name read only by closures to the `(path, start, stop)` spans that
    can name it; a name absent from `scopes` is a reader anywhere in the crate."""
    required = set(REQUIRED_READERS)
    read = {re.escape(name) for mask in masks.values() for name in LOOKUP_PARAMETER.findall(mask)}
    crate_wide = required | read
    scopes: Scopes = {}
    every = [(path, w) for path, mask in masks.items() for w in wrappers(mask)]
    done: set[int] = set()
    while True:
        call = reader_call(required, read)
        found = False
        for index, (path, (kind, name, parameters, start, stop, scope)) in enumerate(every):
            if index in done or name in crate_wide:
                continue
            mask = masks[path]
            inner = []
            for match in call.finditer(mask, start, stop):
                if not visible(scopes, match.group(0), path, match.start()):
                    continue
                opening = mask.find("(", match.end())
                keyed = {bare(a) for a in arguments(mask, opening)[:2]} & parameters
                if keyed or kind == "closure":
                    inner.append(match)  # a closure counts on any read; a fn or macro on a parameter-keyed one
            if not inner:
                continue
            plain = name.rstrip("!").replace("\\", "")
            is_required = "required" in plain or any(m.group("required") for m in inner)
            (required if is_required else read).add(name)
            if scope is None:
                crate_wide.add(name)
                scopes.pop(name, None)
            else:
                scopes.setdefault(name, []).append((path, *scope))
            done.add(index)
            found = True
        if not found:
            return required, read, scopes


def fn_body_brace(mask: str, start: int) -> int:
    """Index of the `{` opening the body of the fn whose `(` is at `start`, or -1 for a fn with no body.

    A `;` ends the search only outside `[]`, `<>` and `()`: `[u8; 4]` and `where` clauses are signature.
    """
    depth = 0
    index = matching_paren(mask, start)
    while index < len(mask):
        char = mask[index]
        if char == "-" and mask[index + 1 : index + 2] == ">":
            index += 2  # the `>` of `->` closes nothing
            continue
        if char in "[<(":
            depth += 1
        elif char in "]>)":
            depth = max(0, depth - 1)
        elif depth == 0 and char == "{":
            return index
        elif depth == 0 and char == ";":
            return -1
        index += 1
    return -1


def enclosing_fn(path: str, text: str, mask: str, position: int) -> tuple[str, str]:
    """`(name, SHA-256 of the whitespace-normalised source)` of the innermost fn whose body contains `position`.

    Fails closed: with no containing body (a top-level site, or a fn this scan cannot span) the name is
    `<top>` and the hash is of `path`, `position` and the whole file, so any change to that file is growth.
    """
    best: tuple[int, str, int] | None = None
    for function in FN_DEFINITION.finditer(mask, 0, position):
        brace = fn_body_brace(mask, function.end() - 1)
        if brace < 0:
            continue
        stop = matching_brace(mask, brace)
        if brace < position < stop and (best is None or function.start() > best[0]):
            best = (function.start(), function.group(1), stop)
    if best is None:
        return "<top>", hashlib.sha256(f"{path}:{position}:{text}".encode()).hexdigest()
    start, name, stop = best
    return name, hashlib.sha256(" ".join(text[start:stop].split()).encode()).hexdigest()


def env_sites(source: dict[str, str]) -> tuple[set[str], set[str], Counter]:
    """`(required keys, every key read, unresolved call sites)` of the non-test source.

    An unresolved site is counted per `(enclosing fn, normalised text)`, so a
    duplicate of an existing site in a new fn is a new site.
    """
    files = production_sources(source)
    masks = {path: code_mask(text) for path, text in files.items()}
    consts: dict[str, set[str]] = {}
    for path, text in files.items():
        for match in CONST_STR.finditer(text):
            if masks[path][match.start()] == text[match.start()]:
                consts.setdefault(match.group(1), set()).add(match.group(2))
    required_names, read_names, scopes = readers_of(files, masks)
    call = reader_call(required_names, read_names)
    required: set[str] = set()
    reads: set[str] = set()
    unresolved: Counter = Counter()
    locations: dict[tuple, set[str]] = {}
    for path, text in files.items():
        mask = masks[path]
        for match in call.finditer(mask):
            if re.search(r"\b(?:fn|macro_rules!)\s*$", mask[max(0, match.start() - 16) : match.start()]):
                continue  # the reader's own definition, not a call
            if not visible(scopes, match.group(0), path, match.start()):
                continue  # a closure reader's name outside the block that binds it
            argument = KEY_ARGUMENT.match(text, match.end())
            prefix, literal, constant = argument.groups() if argument else (None, None, None)
            keys = {literal} if literal else consts.get(constant or "", set())
            if prefix and UPPER_TOKEN.search(prefix):
                keys = set()  # `f(K9, D)`: the key is the first argument, never the second
            if not keys:
                opening = mask.find("(", match.end())
                site = " ".join(text[match.start() : matching_paren(mask, opening)].split())
                name, body = enclosing_fn(path, text, mask, match.start())
                key = (name, site, body)
                unresolved[key] += 1
                locations.setdefault(key, set()).add(path)
                continue
            reads.update(keys)
            if match.group("required"):
                required.update(keys)
    return required, reads, unresolved, {key: sorted(paths) for key, paths in locations.items()}


def env_keys(source: dict[str, str]) -> tuple[set[str], set[str]]:
    """`(required keys, every key read)` at the env-read call sites of the non-test source."""
    required, reads, _, _ = env_sites(source)
    return required, reads


def entry_points(source: dict[str, str]) -> Counter:
    """Calls whose env read happens elsewhere: `*from_env*` / `*from_lookup*`, and any call handed a reader."""
    files = production_sources(source)
    masks = {path: code_mask(text) for path, text in files.items()}
    _, read, _ = readers_of(files, masks)
    passed = {name.replace("\\", "") for name in read if not name.endswith("!")} | {"std::env::var", "env::var"}
    counts: Counter = Counter()
    for mask in masks.values():
        for match in CALL.finditer(mask):
            name = match.group(1)
            if name in NOT_CALLS or re.search(r"\b(?:fn|macro_rules!)\s*$", mask[max(0, match.start() - 16) : match.start()]):
                continue
            opening = match.end() - 1
            if ENTRY_POINT.match(mask, match.start()) or {bare(a) for a in arguments(mask, opening)} & passed:
                counts[name] += 1
    return counts


def tripwire(source: dict[str, str]) -> Counter:
    counts: Counter = Counter()
    for text in production_sources(source).values():
        mask = code_mask(text)
        for token, pattern in TRIPWIRE.items():
            counts[token] += len(pattern.findall(mask))
    return counts


def manifest_of(source: dict[str, str]) -> dict | None:
    return tomllib.loads(source["Cargo.toml"]) if "Cargo.toml" in source else None


def shared_crates(source: dict[str, str]) -> dict[str, dict] | None:
    """`{yadgar-* crate: its spec}` of `Cargo.toml`'s non-dev dependencies; None without one."""
    manifest = manifest_of(source)
    if manifest is None:
        return None
    tables = [manifest.get("dependencies") or {}, manifest.get("build-dependencies") or {}]
    tables += [(t or {}).get("dependencies") or {} for t in (manifest.get("target") or {}).values()]
    crates: dict[str, dict] = {}
    for table in tables:
        for name, spec in table.items():
            package = spec.get("package", name) if isinstance(spec, dict) else name
            if package.startswith("yadgar-"):
                crates[package] = spec if isinstance(spec, dict) else {"version": spec}
    return crates


def pin_of(spec: dict) -> str:
    return f"{spec.get('tag') or spec.get('rev') or '?'} ({spec.get('git') or 'no git'})"


def locked_crates(source: dict[str, str]) -> set[tuple[str, str, str]] | None:
    """`{(name, version, source)}` of every `yadgar-*` package in Cargo.lock but the crate itself."""
    if "Cargo.lock" not in source:
        return None
    own = ((manifest_of(source) or {}).get("package") or {}).get("name")
    packages = tomllib.loads(source["Cargo.lock"]).get("package") or []
    return {
        (p["name"], str(p.get("version")), str(p.get("source")))
        for p in packages
        if p.get("name", "").startswith("yadgar-") and p["name"] != own
    }


def crate_findings(module: str, old_source: dict, new_source: dict) -> list[tuple[str | None, str]]:
    """`(crate or None, reason)` for every shared-crate pin that moved, cannot be pinned, or is overridden."""
    old, new = shared_crates(old_source), shared_crates(new_source)
    if old is None and new is None:
        return []
    if old is None or new is None:
        return [(None, f"{module}: Cargo.toml present at only one of the two tags, so shared crates cannot be compared")]
    findings: list[tuple[str | None, str]] = []
    for name in sorted(old.keys() | new.keys()):
        if old.get(name) != new.get(name):
            moved = f"{pin_of(old[name]) if name in old else 'absent'} -> {pin_of(new[name]) if name in new else 'absent'}"
            findings.append((name, f"{module}: shared crate {name} moved {moved}"))
        spec = new.get(name)
        if spec is not None and (
            spec.get("workspace") or spec.get("branch") or spec.get("path") or not spec.get("git")
            or not (spec.get("tag") or spec.get("rev"))
        ):
            findings.append((name, f"{module}: shared crate {name} has no immutable git tag or rev pin ({spec})"))
    manifest = manifest_of(new_source) or {}
    for table in ("patch", "replace", "workspace"):
        if manifest.get(table):
            findings.append((None, f"{module}: Cargo.toml carries [{table}], which can redirect a shared crate"))
    for kind in ("lib", "bin", "example"):
        targets = manifest.get(kind) or []
        for target in targets if isinstance(targets, list) else [targets]:
            if str(target.get("path", "src/")).split("/")[0] != "src":
                findings.append((None, f"{module}: Cargo.toml [{kind}] path {target.get('path')} is outside src/"))
    old_lock, new_lock = locked_crates(old_source), locked_crates(new_source)
    if old_lock is None or new_lock is None:
        findings.append((None, f"{module}: Cargo.lock missing at one of the two tags, so locked shared crates cannot be compared"))
    else:
        for entry in sorted(old_lock ^ new_lock):
            side = "now locks" if entry in new_lock else "no longer locks"
            findings.append((entry[0], f"{module}: Cargo.lock {side} {entry[0]} {entry[1]} from {entry[2]}"))
    return findings


def crate_moves(module: str, old_source: dict, new_source: dict, only: str | None = None) -> list[str]:
    """The reasons of `crate_findings` (`only`: those naming that crate alone)."""
    return [reason for name, reason in crate_findings(module, old_source, new_source) if only is None or name == only]


def optional(name: str) -> bool:
    return name in OPTIONAL_ENV or name.endswith(OPTIONAL_ENV_SUFFIXES)


def boot_audit(module: str, old_source: dict, new_source: dict, rendered: set[str] | None) -> list[str]:
    """E3 for one moved module: new env names the render does not set, new unreadable sites, moved shared crates."""
    if rendered is None:
        return [f"{module}: a container takes `envFrom`, so the keys it sets cannot be read from the render"]
    if not production_sources(new_source):
        return [f"{module}: no Rust source under src/ at the new tag, so nothing could be audited"]
    old_required, old_reads, old_unresolved, _ = env_sites(old_source)
    new_required, new_reads, new_unresolved, new_paths = env_sites(new_source)
    reasons = [
        f"{module}: required key {key} is new at the new tag and the render does not set it"
        for key in sorted(new_required - old_required)
        if key not in rendered
    ]
    reasons += [
        f"{module}: env read {name} is new at the new tag, not rendered and not a known optional name"
        for name in sorted(new_reads - old_reads - new_required)
        if name not in rendered and not optional(name)
    ]
    reasons += [
        f"{module}: an env read at a new call site whose key E3 cannot resolve: `{site}` ({', '.join(new_paths[key])}, fn {function})"
        for key in sorted(new_unresolved - old_unresolved)
        for (function, site, _hash) in [key]
    ]
    grown_entries = entry_points(new_source) - entry_points(old_source)
    reasons += [
        f"{module}: a new call to shared-crate env entry point `{name}` (x{count}); the keys it reads are not visible here"
        for name, count in sorted(grown_entries.items())
    ]
    grown_tokens = tripwire(new_source) - tripwire(old_source)
    reasons += [
        f"{module}: env tripwire `{token}` grew by {count}; a reader shape E3 does not model may have been added"
        for token, count in sorted(grown_tokens.items())
    ]
    return reasons + crate_moves(module, old_source, new_source)


def rendered_env(documents: list, module: str) -> set[str] | None | bool:
    """Env names the render sets on EVERY container running `module`'s image (each is audited on its own env);
    None if one takes envFrom; False if none runs it."""
    per_container: list[set[str]] = []
    for document in documents:
        if not isinstance(document, dict) or document.get("kind") not in WORKLOAD_KINDS:
            continue
        pod = ((document.get("spec") or {}).get("template") or {}).get("spec") or {}
        for container in (pod.get("containers") or []) + (pod.get("initContainers") or []):
            if split_image(str(container.get("image", "")))[0] != REGISTRY + module:
                continue
            if container.get("envFrom"):
                return None
            per_container.append({entry["name"] for entry in container.get("env") or []})
    return set.intersection(*per_container) if per_container else False


